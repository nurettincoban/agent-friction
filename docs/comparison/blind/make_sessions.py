def validate():
    files = sorted(OUT.glob("*.jsonl"))
    for f in files:
        seen = set()
        tool_ids = {}
        sid = f.stem
        for i, line in enumerate(f.read_text().splitlines(), 1):
            d = json.loads(line)
            if d["type"] == "summary":
                continue
            assert d["sessionId"] == sid, (f, i)
            assert d["cwd"] == CWD
            assert d["parentUuid"] is None or d["parentUuid"] in seen, (f, i, "dangling parent")
            if i > 1 + (1 if f.read_text().startswith('{"type": "summary"') else 0):
                assert d["parentUuid"] is not None, (f, i)
            assert d["uuid"] not in seen
            seen.add(d["uuid"])
            c = d["message"]["content"]
            if d["type"] == "assistant":
                for b in c:
                    if b["type"] == "tool_use":
                        tool_ids[b["id"]] = d["uuid"]
            elif isinstance(c, list):
                for b in c:
                    if b["type"] == "tool_result":
                        assert b["tool_use_id"] in tool_ids, (f, i)
                        assert d["sourceToolAssistantUUID"] == tool_ids[b["tool_use_id"]]
                        assert d["parentUuid"] == tool_ids[b["tool_use_id"]]
        for line in f.read_text().splitlines():
            d = json.loads(line)
            if d["type"] == "summary":
                assert d["leafUuid"] in seen
    return len(files)


