#: (terms to look for, title, rest of the sentence after "<file:line> already ")
Already = tuple[Sequence[str], str, str]
#: Rules whose "already documented" form claims that the files recommend something.
AFFIRMED_RULES = frozenset({"use-the-working-command", "document-the-setup-step"})


def _and(items: Sequence[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def _refs(mentions: Sequence[Mention]) -> str:
    return _and([code(str(m)) for m in mentions])


class _Rules:
    def __init__(
        self,
        findings: Sequence[Finding],
        quote: Quoter | None,
        shares: Mapping[int, float],
        guidance: Guidance | None = None,
        subjects: Sequence[str] = (),
        near: str = "",
        subject_name: str = "",
    ) -> None:
        self.shares = shares
        self.guidance = guidance
        self.subjects = list(subjects)
        self.near = near
        self.subject_name = subject_name
        self.by_signal: dict[str, list[Finding]] = {}
        for finding in findings:
            self.by_signal.setdefault(finding.signal, []).append(finding)
        self.quote = quote
        self.out: list[dict[str, object]] = []

    def get(self, signal: str, variant: str | None = None) -> list[Finding]:
        found = self.by_signal.get(signal, [])
        if variant is None:
            return found
        return [f for f in found if f.detail.get("variant") == variant]

    def add(
        self,
        rule_id: str,
        title: str,
        detail: str,
        based_on: Sequence[str],
        already: Already | None = None,
        **named: str,
    ) -> None:
        """Record a recommendation, in its "already documented" form where that applies.

        ``already`` is the rule's own wording for the case that the instruction files
        name what it would have suggested; any other documentable rule whose subject
        (the path, the command) is named there gets a note instead of new advice.
        """
        assert rule_id in RULE_IDS, rule_id
        mentions: list[Mention] = []
        documented = ""
        guidance = self.guidance
        if guidance is not None and rule_id in DOCUMENTABLE:
            if already is not None:
                # "the working way is written down" needs a line that recommends it, not
                # one that rules it out; "do not edit this file" is the point elsewhere
                # ... and a line that instructs, not one that happens to contain the
                # words ("We make test data with factories" for `make test`).
                mentions = guidance.mentions(
                    list(already[0]),
                    self.near,
                    affirmed=rule_id in AFFIRMED_RULES,
                    context="file" if rule_id == "edit-the-source-not-the-output" else "command",
                )
            if mentions and already is not None:
                title, detail = already[1], f"{_refs(mentions)} already {already[2]}"
                documented = "instruction"
            else:
                terms = [*self.subjects, *(already[0] if already is not None else ())]
                mentions = guidance.mentions(terms, self.near)
                if mentions:
                    documented = "mention"
                    detail += (
                        f" (Also mentioned at {_refs(mentions)}: check whether it already says "
                        "this. If it does, enforce it with a hook, a permission rule or a "
                        "wrapper rather than adding another line.)"
                    )
        self.out.append(
            {
                "id": rule_id,
                "title": title,
                "detail": detail,
                "signals": sorted(set(based_on)),
                "documented_in": [m.as_dict() for m in mentions],
                # "instruction": a line there says what this advice would say (in command
                # or instruction context); "mention": the words occur there, no more
                **({"documented_as": documented} if documented else {}),
                # what the advice names, as data: `replacement`, `setup` (command keys)
                **named,
            }
        )

    # ---- shared rules ----------------------------------------------------------------

    def corrections(self) -> None:
        # Corroborated corrections only: a "probable" one is a separate, weak signal and
        # never the basis of a claim that a human corrected anything.
        found = self.get(signals.USER_CORRECTION)
        if sum(self.shares.get(f.fid, 1.0) for f in found) < CORRECTION_MIN_SHARE:
            return  # nothing, or only thin slices of corrections spread over many files
        # "Keeps repeating" is a claim about the same thing being said twice: it needs two
        # corrections that share wording. Two unrelated corrections are two one-offs.
        repeated = _share_wording([f.detail.get("quote", "") for f in found])
        detail = (
            f"A human corrected the agent here {_in_sessions(found)}. Put the rule in "
            "AGENTS.md / CLAUDE.md (or a comment at the top of the file) so it is read "
            "before the next attempt."
        )
        if not repeated:
            detail = (
                "A human corrected the agent here "
                + ("once" if len(found) == 1 else _in_sessions(found))
                + ("" if len(found) == 1 else ", each time about something else")
                + ". If what they said is a standing rule rather than a one-off, put it in "
                "AGENTS.md / CLAUDE.md (or a comment at the top of the file)."
            )
        if self.quote is not None:
            # Only unambiguous corrections are quoted: a "probable" one may be small talk.
            ranked = sorted(found, key=lambda f: (f.source, f.line))
            quotes: list[str] = []
            for finding in ranked:
                text = self.quote(finding.detail.get("quote", ""), QUOTE_CHARS)
                if text and text not in quotes:
                    quotes.append(text)
            if quotes:
                detail += " In their words: " + " / ".join(f'"{q}"' for q in quotes[:MAX_QUOTES])
        self.add(
            "write-down-the-rule",
            "Write down the rule the human keeps repeating"
            if repeated
            else (
                "Check whether this correction is a standing rule"
                if len(found) == 1
                else "Check whether these corrections are standing rules"
            ),
            detail,
            [signals.USER_CORRECTION],
        )

    def rejections(self) -> None:
        found = self.get(signals.TOOL_REJECTED)
        reasons = [f.detail.get("reason", "") for f in found if f.detail.get("reason")]
        if len(found) < MIN_EVENTS and not reasons:
            return
        detail = (
            f"A human declined the agent's action {_in_sessions(found)}. State the boundary "
            "explicitly (what must not be touched or run, and what to do instead) in "
            "AGENTS.md, or encode it as a permission rule."
        )
        if self.quote is not None and reasons:
            detail += " Reasons given: " + " / ".join(
                f'"{self.quote(r, QUOTE_CHARS)}"' for r, _ in _top(reasons)
            )
        self.add("state-the-boundary", "State the boundary", detail, [signals.TOOL_REJECTED])

    def interrupts(self) -> None:
        found = self.get(signals.USER_INTERRUPT)
        if len(found) < MIN_EVENTS:
            return
        self.add(
            "clarify-before-acting",
            "Tell agents what to check before acting here",
            f"Humans interrupted agents working here {_in_sessions(found)}. Open the cited "
            "transcript lines to see what was being attempted, then document the expected "
            "approach or the precondition that was missed.",
            [signals.USER_INTERRUPT],
        )

    def no_convergence(self, key: str | None) -> None:
        """``key`` is the command for a command hotspot, ``None`` for a file."""
        found = self.get(signals.NO_CONVERGENCE)
        if len(found) < MIN_EVENTS:
            return
        rounds = max(int(f.detail.get("count", "0")) for f in found)
        if key is not None:
            title = f"Agents cannot get {code(key)} to pass"
            opening = f"Agents edited and re-ran {code(key)}"
        else:
            commands = _top([_command_key(f) for f in found], 2)
            names = " / ".join(f"{code(name)}" for name, _ in commands) or "the check"
            title = "Edits here do not get the check to pass"
            opening = f"Agents edited this file and re-ran {names}"
        self.add(
            "explain-the-failing-check",
            title,
            f"{opening} up to {rounds} times in a row without it ever going green "
            f"({_in_sessions(found)}). The failure output did not lead them to a fix. "
            "Document in AGENTS.md how to run and debug this check (one test at a time, "
            "where its fixtures and expected values come from) and what behaviour it "
            "expects, or make its failure message say so.",
            [signals.NO_CONVERGENCE],
        )

    def search_misses(self, where: str) -> None:
        # A search for leftovers (`TODO`, `console.log`) that finds none needs no pointer.
        found = [f for f in self.get(signals.SEARCH_MISS) if "hygiene" not in f.detail]
        if len(found) < MIN_EVENTS:
            return
        detail = f"Agents searched {where} and found nothing {_in_sessions(found)}."
        if self.quote is not None:
            patterns = _top([f.detail.get("pattern", "") for f in found])
            if patterns:
                detail += f" They looked for {_code_list(patterns, self.quote)}."
        detail += (
            " If the concept exists under another name or elsewhere, add a pointer in "
            "AGENTS.md (or a comment/alias where agents look). If it does not exist, say so."
        )
        self.add(
            "add-a-pointer",
            "Point agents to what they are searching for",
            detail,
            [signals.SEARCH_MISS],
        )

    # ---- file rules ------------------------------------------------------------------

    def standing_test(self, when: str) -> bool:
        """The same test is red in session after session and nothing makes it pass."""
        known = [f for f in self.get(signals.COMMAND_FAILURE) if f.detail.get("standing_test")]
        if not known:
            return False
        tests = _top([f.detail["standing_test"] for f in known], 3)
        if self.quote is not None:
            named = _and([code(self.quote(test, QUOTE_CHARS)) for test, _ in tests])
            title = f"{code(self.quote(tests[0][0], QUOTE_CHARS))} is red session after session"
        else:
            named = "The same test" if len(tests) == 1 else "The same tests"
            title = "The same test is red session after session"
        self.add(
            "say-if-it-is-known-broken",
            title,
            f"{named} failed {when} ({_in_sessions(known)}), and nothing in those sessions "
            "made it pass. Fix it, or mark it as a known failure (skip, xfail) and say so in "
            "AGENTS.md, so that agents neither chase it nor learn to ignore a red run.",
            [signals.COMMAND_FAILURE],
        )
        return True

    def file(self, facts: FileFacts | None) -> None:
        self.standing_test("in this file")
        misses = self.get(signals.EDIT_MISS)
        ambiguous = self.get(signals.EDIT_MISS, "ambiguous")
        stale = self.get(signals.STALE_EDIT)
        # A sitting of many edits that ended on a green command did converge.
        thrash = [f for f in self.get(signals.EDIT_THRASH) if not f.detail.get("ended_green")]
        reverts = self.get(signals.EDIT_REVERT)
        too_large = self.get(signals.FILE_TOO_LARGE)
        rework = self.get(signals.HUMAN_REWORK)
        generated = facts is not None and facts.generated
        large = facts is not None and facts.lines is not None and facts.lines >= LARGE_FILE_LINES

        # Only what a transcript shows: a human bumping a lockfile after an agent commit
        # says nothing about anybody having had trouble with the file.
        # A correction alone is enough to fire; the count is of edits that went wrong.
        involved = [*misses, *stale, *reverts] or self.get(signals.USER_CORRECTION)
        if generated and facts is not None and involved:
            sure = facts.generated_by == GENERATED_BY_HEADER
            self.add(
                "edit-the-source-not-the-output",
                "Generated file: point agents at its source"
                if sure
                else "Possibly a generated file: if so, point agents at its source",
                (
                    "This file says it is generated (it starts with a generated-file header)"
                    if sure
                    else f"This file may be generated (judging only by {facts.generated_reason}; "
                    "it carries no generated-file header, so check)"
                )
                + f", yet agents ran into trouble editing it directly {_in_sessions(involved)}. "
                + ("Say" if sure else "If it is, say")
                + " in AGENTS.md which source to change and which command regenerates it, and "
                "consider denying direct edits to it.",
                [f.signal for f in involved],
                (
                    self.subjects,
                    "Generated file: telling agents was not enough",
                    "has an instruction about this file, yet agents ran into trouble editing "
                    f"it directly {_in_sessions(involved)}. Check that the cited line says not "
                    "to edit it by hand. If it does, another line will not help; the next "
                    "step is to enforce it: deny "
                    "direct edits with a permission rule, or add a pre-edit hook that names "
                    "the source to change and the command that regenerates the file. (If "
                    "that line is newer than these sessions, give it time first.)",
                ),
            )
        if len(misses) >= MIN_EVENTS and large and facts is not None:
            self.add(
                "split-or-anchor-large-file",
                "Large file: split it or add unique anchors",
                f"{_n(len(misses), 'edit')} failed to locate the target in this {facts.lines}-line "
                f"file ({len(ambiguous)} matched several places, "
                f"{len(misses) - len(ambiguous)} matched nothing) across "
                f"{_n(_sessions(misses), 'session')}. Split it into smaller modules, or give "
                "repeated blocks unique nearby text (section comments, distinct names) so "
                "an edit can be targeted.",
                [signals.EDIT_MISS],
            )
        elif len(too_large) >= MIN_EVENTS and not generated:
            size = f" ({_n(facts.lines, 'line')})" if facts is not None and facts.lines else ""
            self.add(
                "split-or-anchor-large-file",
                "Large file: agents cannot read it in one piece",
                f"Reads of this file{size} were refused as too large {_in_sessions(too_large)}"
                ", so agents page through it or search it blind. Split it, or say in "
                "AGENTS.md which parts matter and how to find them (section names to search "
                "for).",
                [signals.FILE_TOO_LARGE],
            )
        if len(misses) >= MIN_EVENTS and not generated and not large:
            if len(ambiguous) * 2 >= len(misses):
                detail = (
                    f"{len(ambiguous)} of {len(misses)} failed edits matched several places: "
                    "the file contains repeated blocks. Give them distinguishing text or "
                    "factor the repetition out."
                )
                title = "Repeated blocks: make edit targets unique"
            else:
                detail = (
                    f"{_n(len(misses), 'edit')} in {_n(_sessions(misses), 'session')} did not "
                    "find the "
                    "text the agent expected. Usual causes: a formatter or hook rewrites the "
                    "file after edits, unusual whitespace (tabs, CRLF), or the file changes "
                    "under the agent. Document the formatting step, or run it in a hook so "
                    "the agent sees the result."
                )
                title = "Agents misremember this file: check what rewrites it"
            self.add("make-edits-land", title, detail, [signals.EDIT_MISS])

        modified = self.get(signals.STALE_EDIT, "modified")
        if len(modified) >= MIN_EVENTS and not generated:
            self.add(
                "document-what-rewrites-this-file",
                "Something rewrites this file between read and write",
                f"Writes were refused {_in_sessions(modified)} because the file changed on "
                "disk after the agent read it. Find the writer (formatter on save, watcher, "
                "code generator, a parallel agent) and document it, or make it run "
                "deterministically at a known point.",
                [signals.STALE_EDIT],
            )

        path_misses = self.get(signals.PATH_MISS)
        if len(path_misses) >= MIN_EVENTS:
            self.add(
                "path-agents-expect",
                "Agents expect this path to exist",
                (
                    "Agents tried to `cd` into this non-existent directory "
                    if all(f.detail.get("variant") == "directory" for f in path_misses)
                    else "Agents tried to open this non-existent path "
                )
                + f"{_in_sessions(path_misses)}. "
                + "Add a line to AGENTS.md saying where this actually lives, or create the "
                "file/alias if the guess is the more natural layout.",
                [signals.PATH_MISS],
            )

        self.corrections()
        self.rejections()
        self.denials("to change this file")
        self.interrupts()

        # Thrash in a turn that ran a check was not for want of one, and where the check
        # itself would not pass, `explain-the-failing-check` says what is needed.
        blind = [f for f in thrash if not f.detail.get("checked")]
        stuck = len(self.get(signals.NO_CONVERGENCE)) >= MIN_EVENTS
        if len(blind) + len(reverts) >= MIN_EVENTS and not stuck:
            thrash = blind
            parts = [
                _n(len(thrash), "thrash episode") if thrash else "",
                _n(len(reverts), "reverted edit") if reverts else "",
            ]
            self.add(
                "add-a-fast-check",
                "Give agents a fast way to check changes to this file",
                f"Edits here did not converge: {' and '.join(p for p in parts if p)} in "
                f"{_n(_sessions([*thrash, *reverts]), 'session')}. Document the quickest "
                "command that validates this file (a single test, a type check) so agents "
                "can verify instead of iterating blind.",
                [f.signal for f in (*thrash, *reverts)],
            )

        if len(rework) >= MIN_EVENTS:
            detail = (
                f"Humans changed this file again shortly after {len(rework)} agent commits "
                f"touched it ({_sessions(rework)} distinct agent commits)."
            )
            shas = sorted({f.detail.get("human_commit", "") for f in rework} - {""})
            detail += f" Follow-up commits: {', '.join(shas[:MAX_QUOTES])}."
            detail += (
                " Read those follow-ups: whatever they fix repeatedly is a convention to "
                "document or a test to add."
            )
            self.add(
                "learn-from-rework",
                "Learn from the human follow-ups",
                detail,
                [signals.HUMAN_REWORK],
            )

        self.search_misses("this file")
        self.no_convergence(None)

        loops = self.get(signals.READ_LOOP)
        if len(loops) >= MIN_EVENTS:
            size = f" ({_n(facts.lines, 'line')})" if facts is not None and facts.lines else ""
            self.add(
                "summarize-this-file",
                "Agents keep re-reading this file",
                f"The same part of this file{size} was re-read without progress "
                f"{_in_sessions(loops)}. A short header comment or AGENTS.md note on what "
                "it contains and where the important parts are would save the round trips.",
                [signals.READ_LOOP],
            )

    def denials(self, what: str) -> None:
        denied = self.get(signals.PERMISSION_DENIED)
        if len(denied) < MIN_EVENTS:
            return
        hooks = sum(f.detail.get("variant") == "hook" for f in denied)
        blocked = sum(f.detail.get("variant") == "blocked" for f in denied)
        if blocked * 2 > len(denied):
            self.add(
                "allow-or-document-the-boundary",
                "Tell agents what the harness wants instead",
                f"Agents tried {what} {_in_sessions(denied)} in a form the harness itself "
                "refuses to run (see the cited lines for what it suggests instead). Put that "
                "alternative in AGENTS.md so the first attempt is the right one.",
                [signals.PERMISSION_DENIED],
            )
            return
        by = "a hook" if hooks * 2 > len(denied) else "permission settings"
        self.add(
            "allow-or-document-the-boundary",
            "Allow it, or tell agents it is off limits",
            f"Agents tried {what} {_in_sessions(denied)} and were refused by {by} before "
            "anything ran. If this is routine and safe, add an allow rule so they stop "
            "stalling on it; if it is meant to be off limits, say so in AGENTS.md together "
            "with what to do instead.",
            [signals.PERMISSION_DENIED],
        )

    # ---- command rules ---------------------------------------------------------------

    def environment(self, key: str, failures: list[Finding]) -> None:
        """The command is fine; what it needs around it was not there."""
        kind = _top([f.detail.get("environment", "") for f in failures], 1)[0][0]
        often = _in_sessions(failures)
        if kind == signals.ENV_SERVICE:
            named = _top([f.detail.get("service", "") for f in failures], 1)
            service = named[0][0] if named else "the service it needs"
            title = f"Say how to start {service} before {code(key)}"
            detail = (
                f"{code(key)} failed {often} because {service} was not reachable. Say in "
                "AGENTS.md how to start it and how to check that it is up, or start it before "
                "the agent does. If it cannot run where agents work, say which checks to "
                "run instead."
            )
        elif kind == signals.ENV_AUTH:
            title = f"Say how {code(key)} gets its credentials"
            detail = (
                f"{code(key)} failed {often} because credentials were missing or expired. "
                "Say in AGENTS.md how to log in, or that agents cannot and should stop and "
                "ask instead of retrying."
            )
        elif kind == signals.ENV_PORT:
            title = f"Say what to do when the port {code(key)} needs is taken"
            detail = (
                f"{code(key)} failed {often} because the port it listens on was already in "
                "use, usually by a server left running earlier. Say in AGENTS.md how to check "
                "for and stop it, or let the command pick a free port."
            )
        elif kind == signals.ENV_NETWORK:
            title = f"Say what {code(key)} can reach from where agents work"
            detail = (
                f"{code(key)} failed {often} because a host name could not be resolved: "
                "there is no network where agents run, or that host is not allowed. Say in "
                "AGENTS.md what is reachable and what to do instead (a mirror, a cached "
                "copy, skipping the step), or allow the host."
            )
        elif kind == signals.ENV_DISK:
            title = f"Free disk space where agents run {code(key)}"
            detail = (
                f"{code(key)} failed {often} because the disk was full. Free space on the "
                "machine agents work on, and say in AGENTS.md what is safe to clean (caches, "
                "build output) when it happens again."
            )
        else:
            title = f"Document the environment variables {code(key)} needs"
            variables = _top([f.detail.get("env_var", "") for f in failures], 3)
            which = ""
            if variables and self.quote is not None:
                which = " (" + ", ".join(code(name) for name, _ in variables) + ")"
            detail = (
                f"{code(key)} failed {often} because an environment variable was not set"
                f"{which}. Say in AGENTS.md where the values come from (a template such as "
                "`.env.example`, a secrets manager), or load them in the command itself."
            )
        self.add("document-the-environment", title, detail, [signals.COMMAND_FAILURE])

    def _use_instead(self, better: str, worse: str, failures: Sequence[Finding]) -> Already:
        return (
            [better],
            f"{code(better)} is documented, yet agents run {code(worse)}",
            f"names {code(better)}; agents still ran {code(worse)} and failed "
            f"{_in_sessions(failures)}. Check that the cited line tells agents to use "
            f"{code(better)} here. If it does, another line will not help; the next step is "
            "to enforce it: a hook or "
            f"permission rule that blocks {code(worse)}, or a wrapper that makes "
            f"{code(worse)} do what {code(better)} does. (If that line is newer than these "
            "sessions, give it time first.)",
        )

    def command(self, key: str) -> None:
        failures = self.get(signals.COMMAND_FAILURE)
        invocation = self.get(signals.COMMAND_FAILURE, "invocation")
        invocation = [f for f in invocation if "typo_of" not in f.detail]
        retries = self.get(signals.RETRY_LOOP)
        servers = [f for f in invocation if f.detail.get("server")]
        invocation = [f for f in invocation if not f.detail.get("server")]
        slow = [f for f in invocation if f.detail.get("timeout")]
        invocation = [f for f in invocation if not f.detail.get("timeout")]
        if attribution.is_inline_code(key):
            invocation = []  # ad-hoc code is not a command anyone could document
        if len(slow) >= MIN_EVENTS:
            self.add(
                "give-it-more-time",
                f"{code(key)} outlasts the harness timeout",
                f"{code(key)} was cut off by the harness timeout {_in_sessions(slow)}. Say in "
                "AGENTS.md how long it normally takes and to run it with a longer timeout or "
                "in the background, or point agents at a faster, narrower command for the "
                "inner loop.",
                [signals.COMMAND_FAILURE],
            )
        if len(servers) >= MIN_EVENTS:
            self.add(
                "run-it-in-the-background",
                f"Tell agents to run {code(key)} in the background",
                f"{code(key)} is a server or watcher that never exits; run in the foreground it "
                f"sat until the harness timed it out {_in_sessions(servers)}. Say in "
                "AGENTS.md to start it in the background (and how to check that it is up "
                "and how to stop it), or provide a script that does so.",
                [signals.COMMAND_FAILURE],
            )
        fixes = _top([f.detail.get("recovered_by", "") for f in failures], 1)
        # every step that helped twice or more, in the order agents ran them
        ran = [s for f in failures for s in f.detail.get("fixed_by_setup", "").split(" && ") if s]
        setups = [(s, ran.count(s)) for s in dict.fromkeys(ran) if ran.count(s) >= MIN_EVENTS]
        names = _top([f.detail.get("works_as", "") for f in invocation], 1)
        places = _top([f.detail.get("works_in", "") for f in invocation], 1)
        forms = _top([f.detail.get("works_with", "") for f in invocation], 1)
        environment = self.get(signals.COMMAND_FAILURE, "environment")
        if names and names[0][1] >= MIN_EVENTS:
            # `python: command not found`, then the same line with `python3`
            name, count = names[0]
            shown = [
                f.detail.get("not_found_shown") or f.detail.get("not_found", "") for f in invocation
            ]
            old = (_top(shown, 1) or [(name.rstrip("0123456789."), 0)])[0][0]
            self.add(
                "use-the-working-command",
                f"Tell agents to use {code(name)}",
                f"{code(key)} failed {_in_sessions(invocation)} because {code(old)} is not on "
                f"the PATH here; {_times(count)} the same command then ran with {code(name)}. "
                f'Add a line to AGENTS.md such as: "use {code(name)}, not {code(old)}".',
                [signals.COMMAND_FAILURE],
                self._use_instead(name, old, invocation),
            )
        elif forms and forms[0][1] >= MIN_EVENTS:
            form, count = forms[0]
            self.add(
                "use-the-working-command",
                f"Tell agents to use {code(form)}",
                f"{code(key)} failed {_in_sessions(invocation)} with setup or invocation "
                f"errors; {_times(count)} the same command then ran as {code(form)}, with no "
                "file edited in between. Add a line to AGENTS.md such as: "
                f'"{_agents_line(_place(key), "use " + _typed(form, _place(key)))}", '
                + (
                    "or add the option where the command is defined."
                    if form.startswith(key)
                    else "or put that directory on the PATH before the agent starts."
                    if "/" in form.split()[0] and "=" not in form.split()[0]
                    else "or set the variable where the command is defined."
                ),
                [signals.COMMAND_FAILURE],
                self._use_instead(form, key, invocation),
            )
        elif places and places[0][1] >= MIN_EVENTS:
            place, count = places[0]
            self.add(
                "document-the-command",
                f"Tell agents to run {code(key)} in {code(place)}",
                f"{code(key)} failed {_in_sessions(invocation)} where the agent first ran it; "
                f"{_times(count)} it then worked in {code(place)}. Add a line to AGENTS.md "
                f'such as: "run {code(key)} from {code(place)}".',
                [signals.COMMAND_FAILURE],
            )
        elif fixes and fixes[0][1] >= MIN_EVENTS:
            # Only a command doing the same job counts (see signals: is_replacement), and
            # only in sessions where the failing command never worked afterwards.
            fix, count = fixes[0]
            self.add(
                "use-the-working-command",
                f"Tell agents to use {code(fix)}",
                f"{code(key)} failed {_in_sessions(failures)}; {_times(count)} the agent then "
                f"got the same job done with {code(fix)}, and {code(key)} did not work later in "
                f"those sessions. Add a line to AGENTS.md such as: "
                + '"'
                + _agents_line(
                    _place(key), f"use {_typed(fix, _place(key))}, not {_typed(key, _place(key))}"
                )
                + '".',
                [signals.COMMAND_FAILURE],
                self._use_instead(fix, key, failures),
                replacement=fix,
            )
        elif setups:
            setup, count = setups[0]
            steps = [name for name, _ in setups]
            place = _place(key)
            if len(setups) == 1:
                helped = f"{_times(count)} it worked after the agent ran {code(setup)}"
                line = f"run {_typed(setup, place)} before {_typed(key, place)}"
            else:
                each = [f"{code(name)} ({_times(n)})" for name, n in setups]
                helped = "it worked after the agent ran " + _and(each)
                then = ", then ".join(_typed(name, place) for name in steps)
                line = f"run {then} before {_typed(key, place)}"
            named = _and([code(name) for name in steps])
            self.add(
                "document-the-setup-step",
                f"Document the setup {code(key)} needs",
                f"{code(key)} failed {_in_sessions(failures)}; {helped}. "
                f'Say so in AGENTS.md ("{_agents_line(place, line)}"), or make the environment '
                "ready before the "
                "agent starts.",
                [signals.COMMAND_FAILURE],
                (
                    steps,
                    f"{named} {'is' if len(steps) == 1 else 'are'} documented, yet agents "
                    "start without it",
                    f"names {named}; {code(key)} still failed {_in_sessions(failures)} "
                    "until the agent ran it. Check that the cited line says to run it "
                    "first. If it does, another line will not help: make the environment "
                    "ready before the agent starts (a setup script or a session-start hook), "
                    f"or have {code(key)} run the step itself. (If that line is newer than "
                    "these sessions, give it time first.)",
                ),
                setup=" && ".join(steps),
            )
        elif len(environment) >= MIN_EVENTS:
            self.environment(key, environment)
        elif len(invocation) >= MIN_EVENTS:
            detail = (
                f"{_located(key)} failed {_in_sessions(invocation)} with setup or invocation "
                "errors."
            )
            if self.quote is not None:
                lines = _top([_error_line(f) for f in invocation], 2)
                if lines:
                    detail += " Typical output: " + " / ".join(
                        f'"{self.quote(line, QUOTE_CHARS)}"' for line, _ in lines
                    )
                    detail += "."
            detail += (
                " Document the working invocation (directory, environment, arguments) in "
                "AGENTS.md, or wrap it in a script or make target that sets things up."
            )
            self.add(
                "document-the-command",
                f"Document how to run {_located(key)}",
                detail,
                [signals.COMMAND_FAILURE],
            )
        if retries:
            longest = max(int(f.detail.get("count", "0")) for f in retries)
            self.add(
                "make-the-failure-actionable",
                "Make this failure explain itself",
                f"Agents re-ran {code(key)} up to {longest} times in a row without success "
                f"({_n(len(retries), 'retry loop')} in {_n(_sessions(retries), 'session')}). The "
                "output did not lead them to a fix: note the known cause in AGENTS.md, or "
                "make the command fail fast with a message that says what to do.",
                [signals.RETRY_LOOP],
            )
        standing = [f for f in failures if f.detail.get("recurring_red")]
        if self.standing_test(f"when agents ran {code(key)}"):
            pass  # the test is named: that says more than "keeps ending red"
        elif standing and not self.get(signals.NO_CONVERGENCE):
            self.add(
                "say-if-it-is-known-broken",
                f"{code(key)} keeps ending red",
                f"{code(key)} failed {_in_sessions(standing)} and was still red when each of "
                "those sessions ended. If it is known to be broken, or needs something agents "
                "do not have, say so in AGENTS.md together with what to run instead; "
                "otherwise fix it, so that a red run means something again.",
                [signals.COMMAND_FAILURE],
            )
        rejected = [f for f in failures if f.detail.get("push_rejected") == "recurring"]
        if rejected:
            self.add(
                "pull-before-pushing",
                f"Tell agents to bring the branch up to date before {code(key)}",
                f"{code(key)} was rejected {_in_sessions(rejected)} because the remote branch "
                "had commits the local one lacked (non-fast-forward). Say in AGENTS.md to "
                "fetch and rebase (or merge) before pushing, and whether a force-push is ever "
                "acceptable.",
                [signals.COMMAND_FAILURE],
            )
        flaky = self.get(signals.COMMAND_FAILURE, "flaky")
        if flaky:
            self.add(
                "fix-the-flaky-test",
                f"{code(key)} looks flaky",
                f"{code(key)} fails and then passes on a re-run with nothing changed in "
                f"between ({_in_sessions(flaky)}): it looks flaky. Fix or quarantine the "
                "flaky test, and until then say in AGENTS.md that a red run should be "
                "re-run once before anything is changed.",
                [signals.COMMAND_FAILURE],
            )
        self.no_convergence(key)
        self.rejections()
        self.denials(f"{code(key)}")
        stopped = self.get(signals.USER_INTERRUPT)
        if len(stopped) >= MIN_EVENTS:
            self.add(
                "clarify-before-acting",
                f"Say when agents should run {code(key)}",
                f"Humans stopped {code(key)} while it was running {_in_sessions(stopped)}. If "
                "it takes too long or should not be run here, say so in AGENTS.md together "
                "with what to run instead (a narrower or faster command).",
                [signals.USER_INTERRUPT],
            )


