#: A file with at least this many lines is called "large" in recommendations.
LARGE_FILE_LINES = 800
#: Files bigger than this are not opened to count lines or look for markers.
MAX_FACT_BYTES = 5_000_000
#: Bytes inspected at the top of a file for a "generated" marker.
GENERATED_HEAD_BYTES = 2048
#: Events needed before most rules fire (one-off events do not justify a change).
MIN_EVENTS = 2
