# ------------------------------------------------------------------ session
def h(*parts):
    return hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()


B62 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"


def b62(hexstr, n):
    v = int(hexstr, 16)
    s = ""
    for _ in range(n):
        v, r = divmod(v, 62)
        s += B62[r]
    return s


class Session:
    def __init__(self, vfs, sid, start, branch, summary=None):
        self.vfs = vfs
        self.sid = sid
        self.t = dt.datetime.fromisoformat(start)
        self.branch = branch
        self.lines = []
        self.parent = None
        self.n = 0
        self.summary = summary
        self.read_paths = set()

    # ids / time
    def _uuid(self):
        self.n += 1
        return str(uuid.uuid5(NS, f"{self.sid}:{self.n}"))

    def _tick(self, secs):
        ms = int(h(self.sid, self.n, "ms"), 16) % 900
        self.t += dt.timedelta(seconds=secs, milliseconds=ms)
        return self.t.strftime("%Y-%m-%dT%H:%M:%S.") + f"{self.t.microsecond // 1000:03d}Z"

    def _base(self, typ, secs):
        u = self._uuid()
        d = {
            "parentUuid": self.parent,
            "isSidechain": False,
            "userType": "external",
            "cwd": CWD,
            "sessionId": self.sid,
            "version": VERSION,
            "gitBranch": self.branch,
            "type": typ,
            "uuid": u,
            "timestamp": self._tick(secs),
        }
        return d

    def _emit(self, d):
        self.lines.append(d)
        self.parent = d["uuid"]
        return d

    def _assistant_line(self, block, msg_id, req_id, stop, secs):
        d = self._base("assistant", secs)
        k = int(h(self.sid, self.n), 16)
        d["message"] = {
            "model": MODEL,
            "id": msg_id,
            "type": "message",
            "role": "assistant",
            "content": [block],
            "stop_reason": stop,
            "stop_sequence": None,
            "usage": {
                "input_tokens": 4 + k % 9,
                "cache_creation_input_tokens": 200 + k % 3000,
                "cache_read_input_tokens": 14000 + (k >> 8) % 60000,
                "output_tokens": 40 + (k >> 20) % 900,
                "service_tier": "standard",
            },
        }
        d["requestId"] = req_id
        keys = ["parentUuid", "isSidechain", "userType", "cwd", "sessionId", "version",
                "gitBranch", "message", "requestId", "type", "uuid", "timestamp"]
        return self._emit({k2: d[k2] for k2 in keys})

    def _msg_ids(self):
        x = h(self.sid, self.n, "msg")
        return "msg_01" + b62(x, 22), "req_011C" + b62(x[::-1], 20)

    # human
    def user(self, text, secs=20):
        d = self._base("user", secs)
        d["message"] = {"role": "user", "content": text}
        return self._emit(d)

    def user_marker(self, text, secs=1):
        d = self._base("user", secs)
        d["message"] = {"role": "user", "content": [{"type": "text", "text": text}]}
        return self._emit(d)

    # assistant
    def say(self, text, secs=6):
        mid, rid = self._msg_ids()
        return self._assistant_line({"type": "text", "text": text}, mid, rid, "end_turn", secs)

    def _tool(self, name, inp, content, tur, err=False, text=None, secs=4, run=1):
        mid, rid = self._msg_ids()
        if text:
            self._assistant_line({"type": "text", "text": text}, mid, rid, None, secs)
            secs = 1
        tid = "toolu_01" + b62(h(self.sid, self.n, "tool"), 22)
        a = self._assistant_line({"type": "tool_use", "id": tid, "name": name, "input": inp},
                                 mid, rid, "tool_use", secs)
        d = self._base("user", run)
        block = {"tool_use_id": tid, "type": "tool_result", "content": content}
        if err or name == "Bash":
            block["is_error"] = bool(err)
        d["message"] = {"role": "user", "content": [block]}
        d["toolUseResult"] = tur
        d["sourceToolAssistantUUID"] = a["uuid"]
        return self._emit(d)

    # tools ------------------------------------------------------------------
    def read(self, rel, text=None, secs=4):
        path = P(rel)
        body = self.vfs.get(path)
        self.read_paths.add(path)
        n = body.count("\n") + (0 if body.endswith("\n") else 1)
        tur = {"type": "text", "file": {"filePath": path, "content": body, "numLines": n,
                                        "startLine": 1, "totalLines": n}}
        return self._tool("Read", {"file_path": path}, numbered(body), tur, text=text, secs=secs)

    def edit(self, rel, old, new, text=None, expect=None, secs=5):
        """expect: None (must succeed), 'notfound', 'reject'."""
        path = P(rel)
        inp = {"file_path": path, "old_string": old, "new_string": new}
        cur = self.vfs.get(path)
        if expect == "reject":
            return self._tool("Edit", inp, REJECT_MSG, "User rejected tool use", err=True,
                              text=text, secs=secs, run=9)
        if old not in cur:
            assert expect == "notfound", f"edit miss in {self.sid} {rel}: {old!r}"
            msg = f"String to replace not found in file.\nString: {old}"
            return self._tool("Edit", inp, f"<tool_use_error>{msg}</tool_use_error>",
                              f"Error: {msg}", err=True, text=text, secs=secs)
        assert expect is None, "expected failure but edit applies"
        assert cur.count(old) == 1, f"ambiguous edit {rel}: {old!r}"
        newtext = cur.replace(old, new, 1)
        self.vfs.set(path, newtext)
        tur = {"filePath": path, "oldString": old, "newString": new, "originalFile": cur,
               "structuredPatch": structured_patch(cur, newtext), "userModified": False,
               "replaceAll": False}
        content = (f"The file {path} has been updated. Here's the result of running `cat -n` "
                   f"on a snippet of the edited file:\n{snippet(newtext, new)}")
        return self._tool("Edit", inp, content, tur, text=text, secs=secs)

    def write(self, rel, body, text=None, secs=8):
        path = P(rel)
        orig = self.vfs.files.get(path)
        self.vfs.set(path, body)
        if orig is None:
            tur = {"type": "create", "filePath": path, "content": body, "structuredPatch": [],
                   "originalFile": None}
            content = f"File created successfully at: {path}"
        else:
            tur = {"type": "update", "filePath": path, "content": body,
                   "structuredPatch": structured_patch(orig, body), "originalFile": orig}
            content = (f"The file {path} has been updated. Here's the result of running `cat -n` "
                       f"on a snippet of the edited file:\n{numbered(body)}")
        return self._tool("Write", {"file_path": path, "content": body}, content, tur,
                          text=text, secs=secs)

    def bash(self, cmd, out="", code=0, desc=None, text=None, secs=4, run=3, timeout=None,
             stderr=""):
        inp = {"command": cmd}
        if timeout:
            inp["timeout"] = timeout
        if desc:
            inp["description"] = desc
        if code == 0:
            content = out if not stderr else (out + ("\n" if out else "") + stderr)
            tur = {"stdout": out, "stderr": stderr, "interrupted": False, "isImage": False}
            return self._tool("Bash", inp, content or "(No content)", tur, text=text, secs=secs,
                              run=run)
        if code == "timeout":
            content = f"Command timed out after 2m 0.0s\n{out}"
            return self._tool("Bash", inp, content, f"Error: {content}", err=True, text=text,
                              secs=secs, run=run)
        if code == "interrupt":
            return self._tool("Bash", inp, INTERRUPT_TOOL, f"Error: {INTERRUPT_TOOL}", err=True,
                              text=text, secs=secs, run=run)
        body = out + ("\n" if out and stderr else "") + stderr
        content = f"Exit code {code}\n{body}"
        return self._tool("Bash", inp, content, f"Error: {content}", err=True, text=text,
                          secs=secs, run=run)

    def grep(self, pattern, files, path=None, glob=None, text=None, secs=4):
        inp = {"pattern": pattern}
        if path:
            inp["path"] = path
        if glob:
            inp["glob"] = glob
        abs_files = [P(f) for f in files]
        content = f"Found {len(files)} file{'s' if len(files) != 1 else ''}\n" + "\n".join(abs_files)
        tur = {"mode": "files_with_matches", "filenames": abs_files, "numFiles": len(files)}
        return self._tool("Grep", inp, content, tur, text=text, secs=secs)

    def grep_content(self, pattern, lines, text=None, secs=4):
        inp = {"pattern": pattern, "output_mode": "content", "-n": True}
        body = "\n".join(lines)
        files = sorted({ln.split(":")[0] for ln in lines})
        tur = {"mode": "content", "numFiles": len(files), "filenames": [], "content": body,
               "numLines": len(lines)}
        return self._tool("Grep", inp, body, tur, text=text, secs=secs)

    def glob(self, pattern, files, text=None, secs=3):
        abs_files = [P(f) for f in files]
        tur = {"filenames": abs_files, "durationMs": 11 + len(files), "numFiles": len(files),
               "truncated": False}
        return self._tool("Glob", {"pattern": pattern}, "\n".join(abs_files), tur, text=text,
                          secs=secs)

    def reject_followup(self, text, secs=25):
        self.user_marker(INTERRUPT_TOOL, secs=1)
        return self.user(text, secs=secs)

    # repo actions that change files outside Edit/Write
    def make_schema(self, text=None):
        sch = self.vfs.get(P("schema/readings.avsc"))
        self.vfs.set(P("tidewater/models/generated.py"), codegen(sch))
        return self.bash("make schema",
                         "python3 tools/codegen.py schema/readings.avsc > tidewater/models/generated.py",
                         desc="Regenerate models from the Avro schema", text=text, run=2)

    def lint_ok(self, text=None):
        ok = codegen(self.vfs.get(P("schema/readings.avsc"))) == self.vfs.get(
            P("tidewater/models/generated.py"))
        if ok:
            return self.bash("make lint", "ruff check tidewater tests tools\nAll checks passed!",
                             desc="Run linters", text=text, run=4)
        return self.bash(
            "make lint",
            "tidewater/models/generated.py is stale or hand-edited; run 'make schema'\n"
            "make: *** [Makefile:20: check-generated] Error 1",
            code=2, desc="Run linters", text=text, run=2)

    def dump(self):
        OUT.mkdir(exist_ok=True)
        lines = list(self.lines)
        if self.summary:
            lines.insert(0, {"type": "summary", "summary": self.summary,
                             "leafUuid": self.lines[-1]["uuid"]})
        with open(OUT / f"{self.sid}.jsonl", "w") as fh:
            for d in lines:
                fh.write(json.dumps(d, ensure_ascii=False) + "\n")


def make_test(s, passed, failures=(), secs=0.7, text=None, run=4, deselected=1):
    out = pytest_q(passed, failures, deselected=deselected, secs=secs)
    out = MAKE_TEST + "\n" + out
    if failures:
        out += "\nmake: *** [Makefile:7: test] Error 1"
        return s.bash("make test", out, code=2, desc="Run unit tests", text=text, run=run)
    return s.bash("make test", out, desc="Run unit tests", text=text, run=run)


