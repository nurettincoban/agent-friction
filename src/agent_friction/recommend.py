#: Two corrections are "the same thing again" if they share this many content words, or
#: one long word: a name such as ``PaymentClient`` or ``schema_gen`` rarely recurs by chance.
SHARED_WORDS_MIN = 2
SHARED_NAME_CHARS = 7


def _content_words(text: str) -> set[str]:
    return set(_WORD_RE.findall(text.lower())) - _COMMON_WORDS


def _share_wording(quotes: Sequence[str]) -> bool:
    """Do at least two of these messages talk about the same thing?"""
    words = [_content_words(q) for q in quotes if q]
    for index, first in enumerate(words):
        for second in words[index + 1 :]:
            shared = first & second
            if len(shared) >= SHARED_WORDS_MIN or any(
                len(word) >= SHARED_NAME_CHARS for word in shared
            ):
                return True
    return False


def _command_key(finding: Finding) -> str:
    return next((t.key for t in finding.targets if t.kind == model.COMMAND), "")


_NOISE_LINE_RE = re.compile(r"^(?:\$ |exit code \d+|traceback|\s*file \"|\s*at )", re.I)


def _error_line(finding: Finding) -> str:
    """The most telling line of a failed command's output: the last invocation-error line."""
    lines = [ln.strip() for ln in finding.excerpt.splitlines() if ln.strip()]
    for line in reversed(lines):
        if signals.INVOCATION_ERROR_RE.search(line) and not line.startswith("$ "):
            return line
    for line in reversed(lines):
        if not _NOISE_LINE_RE.match(line):
            return line
    return ""


def recommend(
    kind: str,
    key: str,
    findings: Sequence[Finding],
    facts: FileFacts | None = None,
    quote: Quoter | None = None,
    shares: Mapping[int, float] | None = None,
) -> list[dict[str, object]]:
    """Recommendations for one hotspot.

    ``quote`` redacts and truncates verbatim transcript text; pass ``None`` to
    keep all verbatim text out of the recommendations. ``shares`` maps a
    finding's ``fid`` to the fraction of it attributed to this hotspot
    (default 1).
    """
    if scoring.weak_only(findings):
        return []  # nothing here that productive work does not also produce
    rules = _Rules(findings, quote, shares or {})
    if kind == model.FILE:
        rules.file(facts)
    elif kind == model.COMMAND:
        rules.command(key)
    else:
        rules.search_misses(f"under {key}/" if key != "." else "the whole repo")
        rules.corrections()
    return rules.out
