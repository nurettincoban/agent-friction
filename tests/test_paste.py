def test_the_source_is_kept_only_if_it_exists(tmp_path: Path) -> None:
    (tmp_path / "gen").mkdir()
    header = "# Code generated from {src}. DO NOT EDIT.\n# Run `make gen` to regenerate.\nx = 1\n"
    (tmp_path / "gen" / "out.py").write_text(header.format(src="spec.yaml"))
    facts = file_facts(tmp_path, "gen/out.py")
    assert (facts.source, facts.regenerate) == ("", "make gen")  # spec.yaml is not there
    (tmp_path / "gen" / "spec.yaml").write_text("a: 1\n")
    facts = file_facts(tmp_path, "gen/out.py")
    # found next to the generated file, and given as a path from the repository root
    assert (facts.source, facts.regenerate) == ("gen/spec.yaml", "make gen")
    assert facts.as_dict()["source"] == "gen/spec.yaml"


def test_the_generated_file_advice_names_its_source_and_command() -> None:
    found = [
        signals.Finding(signals.EDIT_MISS, "s", "t", 1, None, "miss", targets=[], detail={}, fid=i)
        for i in range(2)
    ]
    facts = FileFacts(
        True,
        50,
        True,
        "a generated-file header",
        "header",
        source="api/x.yaml",
        regenerate="make gen",
    )
    (rec, *_) = recommend.recommend("file", "src/gen.py", found, facts, quote=lambda t, n: t)
    assert rec["id"] == "edit-the-source-not-the-output"
    assert rec["agents_md"] == (
        "`src/gen.py` is generated from `api/x.yaml`: never edit it by hand; change "
        "`api/x.yaml` and run `make gen` to regenerate it."
    )
    assert rec["deny"] == "Edit(/src/gen.py)"
    assert (rec["source"], rec["regenerate"]) == ("api/x.yaml", "make gen")
    assert "Its header names the fix" in rec["detail"]
    # a header that names neither: the advice as before, with nothing to paste but the rule
    bare = FileFacts(True, 50, True, "a generated-file header", "header")
    (rec, *_) = recommend.recommend("file", "src/gen.py", found, bare, quote=lambda t, n: t)
    assert "which source to change" in rec["detail"] and "source" not in rec
    assert rec["agents_md"] == "`src/gen.py` is generated: never edit it by hand."
    # judged only by its name: nothing to paste, it may not be generated at all
    named = FileFacts(True, 50, True, "its name", "name")
    (rec, *_) = recommend.recommend("file", "src/gen.py", found, named, quote=lambda t, n: t)
    assert "agents_md" not in rec and "deny" not in rec


