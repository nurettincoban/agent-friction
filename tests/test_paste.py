def test_paste_in_the_scan(demo: dict[str, Any]) -> None:
    paste = demo["paste"]
    lines = [item["line"] for item in paste["agents_md"]]
    assert lines[0].startswith("`src/shopfront/api/schema_gen.py` is generated from")
    assert "use `make test`, not `pytest`." in lines
    assert "in `src/shopfront/checkout/service.py`: use `PaymentClient`, not `legacy_charge`." in (
        lines
    )
