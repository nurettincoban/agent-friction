def _declined_step(command: str, subjects: Sequence[str]) -> str:
    """The step of a declined command line that the command hotspot is about, as a
    plain prefix for a deny rule: ``rm -rf migrations/versions`` of
    ``rm -rf migrations/versions && alembic ...``. Every word of the hotspot's key must
    lead the step (``git push`` is not ``git add``); a step with quoting, variables or
    globs is not one a prefix rule can name, and gives ``""``."""
    for step in attribution.parse_command(command).steps:
        words = [step.program, *step.args]
        for subject in subjects:
            key = subject.split()
            if key and words[: len(key)] == key:
                text = " ".join(words)
                plain = all(re.fullmatch(r"[\w./=:@+-]+", word) for word in words)
                # A step behind a wrapper (``sudo``, ``env``, ``bash -c``) is not what
                # was typed, and a prefix rule for it would not stop that call.
                typed = any(
                    piece == text or piece.startswith(text + " ") for piece in typed_pieces(command)
                )
                return text if plain and typed and len(text) <= 120 else ""
    return ""


def _root_name(name: str) -> str:
    """``PaymentClient`` for ``PaymentClient.charge``: a class and its method are one rule."""
    root = name.split(".", 1)[0]
    return root if root[:1].isupper() else name


def _n_sessions_of(
    found: Sequence[Finding],
    key: str,
    value: str,
    norm: Callable[[str], str] = str,
) -> str:
    """ "said in 3 sessions": how many sessions' corrections carry ``key == value``."""
    sessions = {f.session_id for f in found if norm(f.detail.get(key, "")) == value}
    return f"said in {_n(len(sessions), 'session')}"


def generated_line(rel: str, facts: FileFacts) -> str:
    """The AGENTS.md line for a generated file, filled in from what its header says."""
    line = f"{code(rel)} is generated"
    if facts.source:
        line += f" from {code(facts.source)}"
    line += ": never edit it by hand"
    steps = []
    if facts.source:
        steps.append(f"change {code(facts.source)}")
    if facts.regenerate:
        steps.append(f"run {code(facts.regenerate)}")
    if steps:
        line += "; " + " and ".join(steps) + (" to regenerate it" if facts.regenerate else "")
    return line + "."


def _agents_line(place: str, sentence: str) -> str:
    """A line proposed for AGENTS.md: a display key is not something one can type."""
    return f"in {code(place)}, {sentence}" if place else sentence


def _sessions(findings: Sequence[Finding]) -> int:
    return len({f.session_id for f in findings})


def _n(count: int, noun: str, plural: str | None = None) -> str:
    return f"{count} {noun}" if count == 1 else f"{count} {plural or noun + 's'}"


def _times(count: int) -> str:
    return "once" if count == 1 else f"{count} times"


def _in_sessions(findings: Sequence[Finding]) -> str:
    n = _sessions(findings)
    return f"{_times(len(findings))} in {_n(n, 'session')}"


def _top(values: Sequence[str], limit: int = MAX_QUOTES) -> list[tuple[str, int]]:
    counts = Counter(v for v in values if v)
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]


_BLOCKED_SAID_RE = re.compile(r"\bBlocked: [^\n]*?[.!](?:\s+|$)([^\n]+)")


def _harness_instead(excerpt: str) -> str:
    """What a harness block ("Blocked: sleep 30 followed by: ... . To wait, use ...") says
    to do instead: the sentences after the one that refuses, or ``""``."""
    match = _BLOCKED_SAID_RE.search(excerpt)
    return match.group(1).strip() if match else ""


def code(value: str) -> str:
    """``value`` as a Markdown inline code span, whatever it contains.

    The fence is one backtick longer than the longest run of backticks in the
    value, and the value is padded with a space where it starts or ends with
    one (CommonMark strips that padding again).
    """
    runs = re.findall(r"`+", value)
    fence = "`" * (max(map(len, runs), default=0) + 1)
    pad = " " if value.startswith("`") or value.endswith("`") else ""
    return f"{fence}{pad}{value}{pad}{fence}"


def _code_list(pairs: Sequence[tuple[str, int]], quote: Quoter) -> str:
    return ", ".join(
        code(quote(value, QUOTE_CHARS)) + (f" ({count}x)" if count > 1 else "")
        for value, count in pairs
    )


