#: A file with at least this many lines is called "large" in recommendations.
LARGE_FILE_LINES = 800
#: Files bigger than this are not opened to count lines or look for markers.
MAX_FACT_BYTES = 5_000_000
#: Bytes inspected at the top of a file for a "generated" marker.
GENERATED_HEAD_BYTES = 2048
#: Events needed before most rules fire (one-off events do not justify a change).
MIN_EVENTS = 2
#: Verbatim quotes / patterns / commands shown per recommendation, at most.
MAX_QUOTES = 3
#: Summed attribution share of corrections needed before "write down the rule" fires.
CORRECTION_MIN_SHARE = 0.5
QUOTE_CHARS = 160

#: Lines at the top of a file in which a "generated" header is looked for.
GENERATED_HEAD_LINES = 10
#: A generated-file header: a **comment line** that says so in the words generators use.
#: ``// Code generated by protoc-gen-go. DO NOT EDIT.``, ``# @generated``, ``<!-- auto-generated
#: -->``, ``# This file is autogenerated by pip-compile``, ``# Generated by Django 5.0``.
#: Prose ("the summary is generated by the scan", "please do not edit CHANGELOG.md by
#: hand") and the same words inside a string literal are not a header.
_COMMENT = r"^\s*(?:#|//|/\*+|\*|<!--|--|;)\s*"
_GENERATED_MARKER_RE = re.compile(
    _COMMENT + r"(?:"
    r"[^\n]*(?-i:\bDO NOT (?:EDIT|MODIFY)\b)"
    r"|[^\n]*@generated\b"
    r"|[^\n]*\bauto-?generated\b"
    r"|(?:this (?:file|code) (?:is|was) |(?:code|file) )?(?:automatically )?"
    r"generated (?:by|from|with) \S+"
    r")",
    re.I | re.M,
)
#: In prose files ``#`` opens a heading, not a comment.
_PROSE_SUFFIXES = (".md", ".markdown", ".rst", ".txt", ".adoc")
#: Names only a tool writes: a lockfile, a compiled or generated artefact.
_GENERATED_NAME_RE = re.compile(
    r"(?:\.min\.(?:js|css)|_pb2(?:_grpc)?\.pyi?|\.pb\.go|\.g\.dart|\.generated\.[a-z]+"
    r"|[-_.]lock(?:\.json|\.yaml)?|\.lock|\.snap)$"
    r"|(?:^|/)(?:package-lock\.json|pnpm-lock\.yaml|yarn\.lock|poetry\.lock|uv\.lock"
    r"|Cargo\.lock|go\.sum)$"
)
#: Directories that usually hold build output. Usually: `build/package/Dockerfile`,
#: `internal/gen/writer.go` and `cmd/out/main.go` are sources, so the name counts only
#: for a path that git ignores or does not track.
_GENERATED_DIR_RE = re.compile(
    r"(?:^|/)(?:dist|build|out|node_modules|vendor|generated|__generated__|gen)/"
)
GENERATED_BY_HEADER = "header"
GENERATED_BY_NAME = "name"
GENERATED_BY_DIRECTORY = "directory"


def generated_header(rel: str, head: str) -> str:
    """The generated-file header among the first lines of ``head``, or ``""``."""
    top = "\n".join(head.splitlines()[:GENERATED_HEAD_LINES])
    for match in _GENERATED_MARKER_RE.finditer(top):
        prose = rel.lower().endswith(_PROSE_SUFFIXES)
        if prose and not match.group(0).lstrip().startswith("<!--"):
            continue
        return match.group(0).strip()
    return ""


