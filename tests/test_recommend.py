def test_other_file_rules() -> None:
    def recs_for(*found: Finding) -> list[object]:
        return ids(recommend.recommend(model.FILE, "a.py", list(found), FileFacts(True, 50), quote))

    stale = finding(signals.STALE_EDIT, variant="modified")
    assert recs_for(stale, stale) == ["document-what-rewrites-this-file"]
    assert recs_for(finding(signals.STALE_EDIT, variant="not-read")) == []
    miss = finding(signals.PATH_MISS)
    assert recs_for(miss, miss) == ["path-agents-expect"]
    assert recs_for(finding(signals.EDIT_THRASH), finding(signals.EDIT_REVERT)) == [
        "add-a-fast-check"
    ]
    rework = finding(signals.HUMAN_REWORK, human_commit="abc12345")
    assert recs_for(rework, rework) == ["learn-from-rework"]
    loop = finding(signals.READ_LOOP)
    assert recs_for(loop, loop) == []  # weak signals alone justify no advice
    assert recs_for(loop, loop, finding(signals.PATH_MISS)) == ["summarize-this-file"]
    interrupt = finding(signals.USER_INTERRUPT)
    assert recs_for(interrupt) == [] and recs_for(interrupt, interrupt) == ["clarify-before-acting"]
    reject = finding(signals.TOOL_REJECTED, reason="")
    assert recs_for(reject) == []
    assert recs_for(finding(signals.TOOL_REJECTED, reason="never touch this")) == [
        "state-the-boundary"
    ]
    # ordinary failures of commands naming a file (red tests) call for no advice
    failure = finding(signals.COMMAND_FAILURE, variant="ordinary")
    assert recs_for(failure, failure) == []
    denied = finding(signals.PERMISSION_DENIED, variant="permission")
    assert recs_for(denied) == []
    assert recs_for(denied, denied) == ["allow-or-document-the-boundary"]


def test_command_rules() -> None:
    error = "$ pytest -q\nExit code 4\nTraceback\nE   ModuleNotFoundError: No module named 'shop'"
    failures = [
        finding(
            signals.COMMAND_FAILURE,
            f"s{i}",
            variant="invocation",
            excerpt=error,
            recovered_by="make test",
        )
        for i in range(3)
    ]
    (rec,) = recommend.recommend(model.COMMAND, "pytest", failures, None, quote)
    assert (
        rec["id"] == "use-the-working-command" and rec["title"] == "Tell agents to use `make test`"
    )
    assert '"use `make test`, not `pytest`"' in str(rec["detail"])

    for f in failures:
        del f.detail["recovered_by"]
    (rec,) = recommend.recommend(model.COMMAND, "pytest", failures, None, quote)
    assert rec["id"] == "document-the-command"
    assert "ModuleNotFoundError: No module named 'shop'" in str(rec["detail"])
    (rec,) = recommend.recommend(model.COMMAND, "pytest", failures, None, None)
    assert "ModuleNotFoundError" not in str(rec["detail"])

    ordinary = [finding(signals.COMMAND_FAILURE, variant="ordinary") for _ in range(5)]
    assert recommend.recommend(model.COMMAND, "make test", ordinary, None, quote) == []
    retry = finding(signals.RETRY_LOOP, count="4")
    (rec,) = recommend.recommend(model.COMMAND, "make test", [*ordinary, retry], None, quote)
    assert rec["id"] == "make-the-failure-actionable" and "up to 4 times" in str(rec["detail"])


