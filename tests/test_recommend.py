from __future__ import annotations

from pathlib import Path

from agent_friction import model, recommend, redact, signals
from agent_friction.model import Finding, Target
from agent_friction.recommend import FileFacts, file_facts


def finding(signal: str, session: str = "s1", fid: int = 0, **detail: str) -> Finding:
    return Finding(
        signal=signal,
        session_id=session,
        source="x.jsonl",
        line=1,
        ts=None,
        summary="",
        excerpt=detail.pop("excerpt", ""),
        targets=[Target(model.COMMAND, detail.pop("key", "pytest"))],
        detail=dict(detail),
        fid=fid,
    )


def ids(recs: list[dict[str, object]]) -> list[object]:
    return [r["id"] for r in recs]


def quote(text: str, limit: int) -> str:
    return redact.one_line(text, limit)


def test_file_facts(tmp_path: Path) -> None:
    (tmp_path / "gen.py").write_text("# Code generated by protoc. DO NOT EDIT.\n" + "x = 1\n" * 9)
    (tmp_path / "plain.py").write_text("a\nb\nc")
    (tmp_path / "pkg").mkdir()
    (tmp_path / "pkg" / "api_pb2.py").write_text("x\n")
    generated = file_facts(tmp_path, "gen.py")
    assert (generated.exists, generated.lines, generated.generated) == (True, 10, True)
    assert "marker" in generated.generated_reason
    assert file_facts(tmp_path, "plain.py") == FileFacts(True, 3, False, "")
    assert file_facts(tmp_path, "pkg/api_pb2.py").generated
    assert file_facts(tmp_path, "pkg").exists is False
    missing = file_facts(tmp_path, "dist/app.min.js")
    assert (missing.exists, missing.lines, missing.generated) == (False, None, True)
    for lock in ("package-lock.json", "sub/yarn.lock", "poetry.lock", "go.sum"):
        assert file_facts(tmp_path, lock).generated
    assert not file_facts(tmp_path, "src/locksmith.py").generated
    assert generated.as_dict() == {"exists": True, "lines": 10, "generated": True}


def test_generated_file_rule_wins_over_generic_edit_advice() -> None:
    found = [finding(signals.EDIT_MISS, f"s{i}", variant="not-found") for i in range(3)]
    facts = FileFacts(True, 2000, True, 'a "do not edit" marker')
    recs = recommend.recommend(model.FILE, "gen.py", found, facts)
    assert ids(recs) == ["edit-the-source-not-the-output", "split-or-anchor-large-file"]
    assert "3 times in 3 sessions" in str(recs[0]["detail"])
    assert "2000-line" in str(recs[1]["detail"])
    assert recs[0]["signals"] == [signals.EDIT_MISS]


def test_edit_miss_rules_for_ordinary_files() -> None:
    small = FileFacts(True, 120)
    ambiguous = [finding(signals.EDIT_MISS, variant="ambiguous") for _ in range(2)]
    (rec,) = recommend.recommend(model.FILE, "a.py", ambiguous, small)
    assert rec["id"] == "make-edits-land" and "repeated blocks" in str(rec["detail"])
    not_found = [finding(signals.EDIT_MISS, variant="not-found") for _ in range(2)]
    (rec,) = recommend.recommend(model.FILE, "a.py", not_found, small)
    assert "formatter" in str(rec["detail"])
    assert recommend.recommend(model.FILE, "a.py", not_found[:1], small) == []  # one-off


def test_correction_rule_quotes_redacted_words_and_respects_shares() -> None:
    found = [
        finding(signals.USER_CORRECTION, quote="No! use  make test,\nmy password=hunter2", fid=1),
        finding(signals.USER_CORRECTION, "s2", quote="I said use make test", fid=2),
    ]
    (rec,) = recommend.recommend(model.FILE, "a.py", found, None, quote)
    detail = str(rec["detail"])
    assert rec["id"] == "write-down-the-rule" and "2 times in 2 sessions" in detail
    assert '"No! use make test, my password=[REDACTED]"' in detail and "hunter2" not in detail
    (plain,) = recommend.recommend(model.FILE, "a.py", found, None, None)
    assert "make test" not in str(plain["detail"])  # no verbatim text without a quoter
    thin = recommend.recommend(model.FILE, "a.py", found[:1], None, quote, {1: 0.25})
    assert thin == []
    assert recommend.recommend(model.FILE, "a.py", found, None, quote, {1: 0.25, 2: 0.25})


def test_other_file_rules() -> None:
    def recs_for(*found: Finding) -> list[object]:
        return ids(recommend.recommend(model.FILE, "a.py", list(found), FileFacts(True, 50), quote))

    stale = finding(signals.STALE_EDIT, variant="modified")
    assert recs_for(stale, stale) == ["document-what-rewrites-this-file"]
    assert recs_for(finding(signals.STALE_EDIT, variant="not-read")) == []
    miss = finding(signals.PATH_MISS)
    assert recs_for(miss, miss) == ["path-agents-expect"]
    assert recs_for(finding(signals.EDIT_THRASH), finding(signals.EDIT_REVERT)) == [
        "add-a-fast-check"
    ]
    rework = finding(signals.HUMAN_REWORK, human_commit="abc12345")
    assert recs_for(rework, rework) == ["learn-from-rework"]
    loop = finding(signals.READ_LOOP)
    assert recs_for(loop, loop) == ["summarize-this-file"]
    interrupt = finding(signals.USER_INTERRUPT)
    assert recs_for(interrupt) == [] and recs_for(interrupt, interrupt) == ["clarify-before-acting"]
    reject = finding(signals.TOOL_REJECTED, reason="")
    assert recs_for(reject) == []
    assert recs_for(finding(signals.TOOL_REJECTED, reason="never touch this")) == [
        "state-the-boundary"
    ]
    # ordinary failures of commands naming a file (red tests) call for no advice
    failure = finding(signals.COMMAND_FAILURE, variant="ordinary")
    assert recs_for(failure, failure) == []
    denied = finding(signals.PERMISSION_DENIED, variant="permission")
    assert recs_for(denied) == []
    assert recs_for(denied, denied) == ["allow-or-document-the-boundary"]


def test_command_rules() -> None:
    error = "$ pytest -q\nExit code 4\nTraceback\nE   ModuleNotFoundError: No module named 'shop'"
    failures = [
        finding(
            signals.COMMAND_FAILURE,
            f"s{i}",
            variant="invocation",
            excerpt=error,
            recovered_by="make test",
        )
        for i in range(3)
    ]
    (rec,) = recommend.recommend(model.COMMAND, "pytest", failures, None, quote)
    assert (
        rec["id"] == "use-the-working-command" and rec["title"] == "Tell agents to use `make test`"
    )
    assert '"use `make test`, not `pytest`"' in str(rec["detail"])

    for f in failures:
        del f.detail["recovered_by"]
    (rec,) = recommend.recommend(model.COMMAND, "pytest", failures, None, quote)
    assert rec["id"] == "document-the-command"
    assert "ModuleNotFoundError: No module named 'shop'" in str(rec["detail"])
    (rec,) = recommend.recommend(model.COMMAND, "pytest", failures, None, None)
    assert "ModuleNotFoundError" not in str(rec["detail"])

    ordinary = [finding(signals.COMMAND_FAILURE, variant="ordinary") for _ in range(5)]
    assert recommend.recommend(model.COMMAND, "make test", ordinary, None, quote) == []
    retry = finding(signals.RETRY_LOOP, count="4")
    (rec,) = recommend.recommend(model.COMMAND, "make test", [*ordinary, retry], None, quote)
    assert rec["id"] == "make-the-failure-actionable" and "up to 4 times" in str(rec["detail"])


def test_directory_search_rule_lists_patterns() -> None:
    found = [
        finding(signals.SEARCH_MISS, "s1", pattern="RefundPolicy"),
        finding(signals.SEARCH_MISS, "s2", pattern="RefundPolicy"),
        finding(signals.SEARCH_MISS, "s2", pattern="refund_policy"),
    ]
    (rec,) = recommend.recommend(model.DIR, "src/shop", found, None, quote)
    detail = str(rec["detail"])
    assert rec["id"] == "add-a-pointer" and "under src/shop/" in detail
    assert "`RefundPolicy` (2x), `refund_policy`" in detail
    (plain,) = recommend.recommend(model.DIR, ".", found, None, None)
    assert "RefundPolicy" not in str(plain["detail"]) and "the whole repo" in str(plain["detail"])
    assert recommend.recommend(model.DIR, "src", found[:1], None, quote) == []
