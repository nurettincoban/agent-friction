"""Rule-based recommendations.

Each rule looks at the mix of findings on one hotspot and, when its evidence
threshold is met, emits a concrete suggestion that cites the counts (and, when
excerpts are enabled, the actual commands, patterns and human words) behind
it. Rules and thresholds are listed in docs/methodology.md.
"""

