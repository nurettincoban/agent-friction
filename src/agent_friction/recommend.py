@dataclass(frozen=True)
class FileFacts:
    """What we know about a hotspot file from the working tree."""

    exists: bool
    lines: int | None = None
    generated: bool = False
    generated_reason: str = ""
    #: What says so: a header in the file, its name, or its (untracked) directory.
    generated_by: str = ""

    def as_dict(self) -> dict[str, object]:
        return {"exists": self.exists, "lines": self.lines, "generated": self.generated}


def in_output_directory(rel: str) -> bool:
    """Is ``rel`` under a directory named like build output (``dist/``, ``gen/``, ...)?"""
    return _GENERATED_DIR_RE.search(rel) is not None


def file_facts(repo: Path, rel: str, untracked: bool = False) -> FileFacts:
    """Inspect ``repo/rel`` (size, generated header). Never raises.

    A file counts as generated on one of three grounds: a header that says so
    (``generated_header``), a name only tools write (a lockfile, ``*_pb2.py``,
    ``*.min.js``), or a directory named like build output **if** git ignores or
    does not track the path (``untracked``; the caller knows).
    """
    by, reason = "", ""
    if _GENERATED_NAME_RE.search(rel):
        by, reason = GENERATED_BY_NAME, "its name"
    elif untracked and in_output_directory(rel):
        by, reason = GENERATED_BY_DIRECTORY, "its directory, which git does not track"
    path = repo / rel
    try:
        if not path.is_file():
            return FileFacts(False, None, bool(by), reason, by)
        if path.stat().st_size > MAX_FACT_BYTES:
            return FileFacts(True, None, bool(by), reason, by)
        data = path.read_bytes()
    except OSError:
        return FileFacts(False, None, bool(by), reason, by)
    lines = data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
    head = data[:GENERATED_HEAD_BYTES].decode("utf-8", "replace")
    if generated_header(rel, head):
        return FileFacts(True, lines, True, "a generated-file header", GENERATED_BY_HEADER)
    return FileFacts(True, lines, bool(by), reason, by)


_IN_DIRECTORY_RE = re.compile(r"^(.+) \((.+/)\)$")


def _located(key: str) -> str:
    """``pytest (src/)`` in a sentence: "`pytest` in `src/`"."""
    match = _IN_DIRECTORY_RE.match(key)
    if match is None:
        return code(key)
    return f"{code(match.group(1))} in {code(match.group(2))}"


def _place(key: str) -> str:
    """The directory a display key says its command ran in (``web/``), or ``""``."""
    match = _IN_DIRECTORY_RE.match(key)
    return match.group(2) if match else ""


def _typed(key: str, place: str) -> str:
    """``key`` as it is typed in ``place``: without the ``(web/)`` suffix of a display key."""
    match = _IN_DIRECTORY_RE.match(key)
    if match is not None and match.group(2) == place:
        return code(match.group(1))
    return _located(key)


def _agents_line(place: str, sentence: str) -> str:
    """A line proposed for AGENTS.md: a display key is not something one can type."""
    return f"in {code(place)}, {sentence}" if place else sentence


def _sessions(findings: Sequence[Finding]) -> int:
    return len({f.session_id for f in findings})


def _n(count: int, noun: str, plural: str | None = None) -> str:
    return f"{count} {noun}" if count == 1 else f"{count} {plural or noun + 's'}"


def _times(count: int) -> str:
    return "once" if count == 1 else f"{count} times"


def _in_sessions(findings: Sequence[Finding]) -> str:
    n = _sessions(findings)
    return f"{_times(len(findings))} in {_n(n, 'session')}"


def _top(values: Sequence[str], limit: int = MAX_QUOTES) -> list[tuple[str, int]]:
    counts = Counter(v for v in values if v)
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]


def code(value: str) -> str:
    """``value`` as a Markdown inline code span, whatever it contains.

    The fence is one backtick longer than the longest run of backticks in the
    value, and the value is padded with a space where it starts or ends with
    one (CommonMark strips that padding again).
    """
    runs = re.findall(r"`+", value)
    fence = "`" * (max(map(len, runs), default=0) + 1)
    pad = " " if value.startswith("`") or value.endswith("`") else ""
    return f"{fence}{pad}{value}{pad}{fence}"


def _code_list(pairs: Sequence[tuple[str, int]], quote: Quoter) -> str:
    return ", ".join(
        code(quote(value, QUOTE_CHARS)) + (f" ({count}x)" if count > 1 else "")
        for value, count in pairs
    )


