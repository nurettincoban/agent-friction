def test_weak_cues_about_code_the_agent_just_added(tmp_path: Path) -> None:
    def session(follow_up: bool, name: str = "legacy_charge") -> Session:
        s = Session().user("add gift messages")
        s.edit(A, "total = cart.total()", "total = cart.total()\n    legacy_charge(total)")
        s.edit(B, "class Order:", "class Order:\n    gift_message: str")
        s.say("Done: orders accept gift_message.")
        s.user(f"Actually {name}() is deprecated, PaymentClient.charge() is what we use instead.")
        if follow_up:
            s.edit(A, "    legacy_charge(total)", "    payments.charge(total)")
        return s

    (fix,) = detect(session(True), tmp_path)
    assert fix.signal == signals.USER_CORRECTION
    # about the file the name went into, not every file of the turn
    assert [t.key for t in fix.targets] == ["src/a.py"]
    assert fix.detail["ruled_out"] == "legacy_charge"
    assert fix.detail["use_instead"] == "PaymentClient.charge"
    assert "names code the agent had just added" in fix.summary
    assert "legacy_charge" not in fix.summary  # the summary is structural
    # the agent did not go back: what the cues alone give, a probable correction
    (left,) = detect(session(False), tmp_path)
    assert left.signal == signals.PROBABLE_CORRECTION and left.excerpt == ""
    # a name the agent did not add is not about its code: the cues alone, as before
    (other,) = detect(session(True, name="other_helper"), tmp_path)
    assert other.signal == signals.PROBABLE_CORRECTION


def test_said_done_then_still_failing(tmp_path: Path) -> None:
    def session(claim: str, reply: str, work_between: bool = False) -> Session:
        s = Session().user("add discount codes")
        s.edit(A, "charge = payments.charge", "charge = legacy_charge")
        s.bash("make test 2>&1 | tail -5", "42 passed")
        s.say(claim)
        if work_between:
            s.bash("git status")
        s.user(reply)
        s.edit(A, "charge = legacy_charge", "charge = payments.charge")
        return s

    failing = "It's still failing for me on staging, I told you: PaymentClient only."
    (fix,) = detect(session("Discount codes work and all tests pass.", failing), tmp_path)
    assert fix.signal == signals.USER_CORRECTION
    assert fix.detail["claimed_done"] == "1" and fix.detail["checked_with"] == "make test"
    # no claim of being done, or no report of a failure: an ordinary correction
    (plain,) = detect(session("I changed the charge call.", failing), tmp_path)
    assert "claimed_done" not in plain.detail
    redirect = "No, I told you: PaymentClient only."
    (other,) = detect(session("Discount codes work and all tests pass.", redirect), tmp_path)
    assert "claimed_done" not in other.detail
    # the agent went on working after its claim: the claim did not stand
    (later,) = detect(session("All tests pass.", failing, work_between=True), tmp_path)
    assert "claimed_done" not in later.detail


def _correction(i: int, **detail: str) -> signals.Finding:
    return signals.Finding(
        signals.USER_CORRECTION,
        f"s{i}",
        "t",
        i,
        None,
        "corrected",
        targets=[],
        detail={"quote": "No, I told you: use PaymentClient", "confidence": "1", **detail},
        fid=i,
    )


def test_the_rule_is_stated_from_the_corrections() -> None:
    found = [
        _correction(1, ruled_out="legacy_charge", use_instead="PaymentClient.charge"),
        _correction(2, use_instead="PaymentClient"),
        _correction(3, ruled_out="legacy_charge", use_instead="PaymentClient"),
    ]
    quote = lambda text, n: text  # noqa: E731
    (rule, *_) = recommend.recommend("file", "src/a.py", found, FileFacts(True, 10), quote)
    assert rule["id"] == "write-down-the-rule"
    assert (
        "The rule, as they put it: use `PaymentClient` (said in 3 sessions), not "
        "`legacy_charge` (said in 2 sessions)." in rule["detail"]
    )
    assert rule["agents_md"] == "in `src/a.py`: use `PaymentClient`, not `legacy_charge`."
    # without excerpts nothing the human said is repeated
    (bare, *_) = recommend.recommend("file", "src/a.py", found, FileFacts(True, 10), None)
    assert "agents_md" not in bare and "PaymentClient" not in json.dumps(bare)


def test_how_to_verify_follows_a_claim_that_did_not_hold() -> None:
    found = [_correction(1, claimed_done="1", checked_with="make test"), _correction(2)]
    quote = lambda text, n: text  # noqa: E731
    recs = recommend.recommend("file", "src/a.py", found, FileFacts(True, 10), quote)
    (verify,) = [r for r in recs if r["id"] == "say-how-to-verify"]
    assert verify["events"] == 1 and "evidence" not in verify  # the human's word carries it
    assert "saw pass was `make test`" in verify["detail"]
    assert "passing `make test` was not enough here" in verify["agents_md"]
    recs = recommend.recommend("file", "src/a.py", found[1:], FileFacts(True, 10), quote)
    assert "say-how-to-verify" not in {r["id"] for r in recs}


# ---- declined commands ---------------------------------------------------------------


def _declined(reason: str, command: str = "rm -rf migrations/versions && alembic up") -> Any:
    return signals.Finding(
        signals.TOOL_REJECTED,
        "s",
        "t",
        1,
        None,
        "declined",
        targets=[],
        detail={"reason": reason, "command": command},
        fid=1,
    )


def test_a_boundary_with_a_forbidding_reason_gets_a_deny_rule() -> None:
    quote = lambda text, n: text  # noqa: E731
    found = [_declined("never delete existing migrations, add a new revision on top")]
    (rec,) = recommend.recommend("command", "rm", found, None, quote)
    assert rec["deny"] == "Bash(rm -rf migrations/versions:*)"
    assert rec["agents_md"] == (
        "never run `rm -rf migrations/versions`: never delete existing migrations, add a "
        "new revision on top."
    )
    # "not now" defers, it does not forbid
    (rec,) = recommend.recommend("command", "rm", [_declined("not now, later")], None, quote)
    assert "deny" not in rec and "agents_md" not in rec
    # without excerpts, nothing (the line would quote the human)
    (rec,) = recommend.recommend("command", "rm", found, None, None)
    assert "deny" not in rec


