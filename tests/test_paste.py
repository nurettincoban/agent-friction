    assert edit["rule"] == "Edit(/src/shopfront/api/schema_gen.py)"
    # replayed: what it would have refused, all on that file, and the Aider session apart
    assert edit["refused_targets"] == [
        {"target": "src/shopfront/api/schema_gen.py", "calls": edit["would_refuse"]}
    ]
    assert edit["would_refuse"] >= 6 and edit["other_agent_sessions"] == 1
    assert rm["rule"] == "Bash(rm -rf migrations/versions:*)"
    assert (rm["would_refuse"], rm["sessions"]) == (1, 1)


