def test_code_names_and_what_to_use_instead() -> None:
    text = "Actually legacy_charge() is deprecated, PaymentClient.charge() is what we use instead."
    assert signals.code_names(text) == ["legacy_charge", "PaymentClient.charge"]
    assert signals.use_instead(text, "legacy_charge") == "PaymentClient.charge"
    assert signals.use_instead("No, use `PaymentClient`, not the old one", "") == "PaymentClient"
    assert signals.use_instead("I told you: PaymentClient only.", "x_y") == "PaymentClient"
    # ordinary words, paths and file names are not names in code shape
    assert signals.code_names("No, use the other module in src/app/main.py please") == []
    assert signals.use_instead("use tabs instead", "") == ""


