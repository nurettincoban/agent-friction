def _and(items: Sequence[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def _refs(mentions: Sequence[Mention]) -> str:
    return _and([code(str(m)) for m in mentions])


class _Rules:
    def __init__(
        self,
        findings: Sequence[Finding],
        quote: Quoter | None,
        shares: Mapping[int, float],
        guidance: Guidance | None = None,
        subjects: Sequence[str] = (),
        near: str = "",
        subject_name: str = "",
        known_targets: Sequence[str] = (),
    ) -> None:
        self.known_targets = tuple(known_targets)
        self.shares = shares
        self.guidance = guidance
        self.subjects = list(subjects)
        self.near = near
        self.subject_name = subject_name
        #: The hotspot's file (``""`` for a command or a directory).
        self.key = ""
        self.by_signal: dict[str, list[Finding]] = {}
        for finding in findings:
            if finding.detail.get(scoring.WITHIN_BASELINE) == "1":
                continue  # no more than the repository's background rate: see `repo_wide`
            self.by_signal.setdefault(finding.signal, []).append(finding)
        self.quote = quote
        self.out: list[dict[str, object]] = []

    def get(self, signal: str, variant: str | None = None) -> list[Finding]:
        found = self.by_signal.get(signal, [])
        if variant is None:
            return found
        return [f for f in found if f.detail.get("variant") == variant]

    def add(
        self,
        rule_id: str,
        title: str,
        detail: str,
        based_on: Sequence[str],
        already: Already | None = None,
        against: tuple[str, str, str, str, str] | None = None,
        events: int | None = None,
        stated: bool = False,
        paste: Mapping[str, str] | None = None,
        **named: str,
    ) -> None:
        """Record a recommendation, in its "already documented" form where that applies.

        ``already`` is the rule's own wording for the case that the instruction files
        name what it would have suggested; any other documentable rule whose subject
        (the path, the command) is named there gets a note instead of new advice.
        ``events`` is how many events the advice rests on (default: this hotspot's
        events of the ``based_on`` signals); ``stated`` says a human gave the reason in
        so many words, which carries the advice however few the events are.
        """
        assert rule_id in RULE_IDS, rule_id
        if events is None:
            events = len({f.fid for signal in based_on for f in self.get(signal)})
        sessions = len({f.unit for signal in based_on for f in self.get(signal)})
        thin = (
            events < THIN_EVIDENCE_EVENTS
            and not stated
            and rule_id not in FACT_BACKED_RULES
            # the job done another way, with nothing changed, in two sessions: a fact of
            # how this repository runs, not a guess
            and not (rule_id in SEEN_WORKING_RULES and sessions >= 2)
        )
        mentions: list[Mention] = []
        documented = ""
        guidance = self.guidance
        if guidance is not None and against is not None:
            # The files tell agents to run the very command that fails here, or rule out
            # the one that worked: proposing "use the other one" would contradict them.
            told, proposed, title_told, text_told, text_ruled_out = against
            mentions = guidance.conflicts(told, "", self.near)
            ruled_out = [] if mentions else guidance.conflicts("", proposed, self.near)
            if mentions:
                title, detail = title_told, f"{_refs(mentions)} {text_told}"
            elif ruled_out:
                mentions = ruled_out
                title = f"{code(proposed)} is ruled out, yet it is what works"
                detail = f"{_refs(mentions)} {text_ruled_out}"
            if mentions:
                documented = "conflict"
                named = {}
        if documented:
            pass
        elif guidance is not None and rule_id in DOCUMENTABLE:
            if already is not None:
                # "the working way is written down" needs a line that recommends it, not
                # one that rules it out; "do not edit this file" is the point elsewhere
                # ... and a line that instructs, not one that happens to contain the
                # words ("We make test data with factories" for `make test`).
                mentions = guidance.mentions(
                    list(already[0]),
                    self.near,
                    affirmed=rule_id in AFFIRMED_RULES,
                    context="file"
                    if rule_id == "edit-the-source-not-the-output"
                    else "step"
                    if rule_id == "document-the-setup-step"
                    else "command",
                )
            if mentions and already is not None:
                title, detail = already[1], f"{_refs(mentions)} already {already[2]}"
                documented = "instruction"
            else:
                terms = [*self.subjects, *(already[0] if already is not None else ())]
                mentions = guidance.mentions(terms, self.near)
                enforced = any(
                    "deliberate" in f.detail for f in self.get(signals.PERMISSION_DENIED)
                ) or all(m.file in SETTINGS_FILES for m in mentions)
                if mentions and enforced:
                    # what is cited is the deny rule itself, or a hook or a rule already
                    # refuses this: "enforce it" is what was done
                    documented = "mention"
                    detail += f" (Also mentioned at {_refs(mentions)}.)"
                elif mentions:
                    documented = "mention"
                    detail += (
                        f" (Also mentioned at {_refs(mentions)}: check whether it already says "
                        "this. If it does, enforce it with a hook, a permission rule or a "
                        "wrapper rather than adding another line.)"
                    )
        self.out.append(
            {
                "id": rule_id,
                "title": title,
                "detail": detail,
                "signals": sorted(set(based_on)),
                "events": events,
                **({"evidence": "thin"} if thin else {}),
                "documented_in": [m.as_dict() for m in mentions],
                # "instruction": a line there says what this advice would say (in command
                # or instruction context); "mention": the words occur there, no more;
                # "conflict": a line there says the opposite of what the sessions show
                **({"documented_as": documented} if documented else {}),
                # what the advice names, as data: `replacement`, `setup` (command keys)
                **named,
                # text to paste (`agents_md`, `deny`), unless written down already
                **(dict(paste) if paste and documented not in ("instruction", "conflict") else {}),
            }
        )

    # ---- shared rules ----------------------------------------------------------------

    def corrections(self) -> None:
        # Corroborated corrections only: a "probable" one is a separate, weak signal and
        # never the basis of a claim that a human corrected anything.
        found = self.get(signals.USER_CORRECTION)
        if sum(self.shares.get(f.fid, 1.0) for f in found) < CORRECTION_MIN_SHARE:
            return  # nothing, or only thin slices of corrections spread over many files
        # "Keeps repeating" is a claim about the same thing being said twice: it needs two
        # corrections that share wording. Two unrelated corrections are two one-offs.
        repeated = _share_wording([f.detail.get("quote", "") for f in found])
        # Said while the agent worked on this file, about a file it had not touched: the
        # words may name that other file, so the reader is told which.
        named = _top([f.detail.get("also_named", "") for f in found])
        here = (
            "while it was working here"
            if len(named) and all(f.detail.get("also_named") for f in found)
            else "here"
        )
        said = ""
        detail = (
            f"A human corrected the agent {here} {_in_sessions(found)}. Put the rule in "
            "AGENTS.md / CLAUDE.md (or a comment at the top of the file) so it is read "
            "before the next attempt."
        )
        if not repeated:
            detail = (
                f"A human corrected the agent {here} "
                + ("once" if len(found) == 1 else _in_sessions(found))
                + (", each time about something else" if _differ(found) else "")
                + ". If what they said is a standing rule rather than a one-off, put it in "
                "AGENTS.md / CLAUDE.md (or a comment at the top of the file)."
            )
        if self.quote is not None:
            # Only unambiguous corrections are quoted: a "probable" one may be small talk.
            ranked = sorted(found, key=lambda f: (f.source, f.line))
            quotes: list[str] = []
            for finding in ranked:
                text = self.quote(finding.detail.get("quote", ""), QUOTE_CHARS)
                if text and text not in quotes:
                    quotes.append(text)
            if quotes:
                said = " In their words: " + " / ".join(f'"{q}"' for q in quotes[:MAX_QUOTES])
                detail += said
        if named:
            detail += (
                f" (The human also named {_and([code(name) for name, _ in named])}, which "
                "the agent had not touched.)"
            )
        paste: dict[str, str] = {}
        if self.quote is not None:
            # What the human ruled out (a name the agent had just written) and what they
            # said to use: the rule itself, in its own words, across sessions.
            out = _top([f.detail.get("ruled_out", "") for f in found], 1)
            # `PaymentClient.charge()` and `PaymentClient` are one rule: the class
            use = _top([_root_name(f.detail.get("use_instead", "")) for f in found], 1)
            q = self.quote
            if out or use:
                parts = []
                if use:
                    parts.append(
                        f"use {code(q(use[0][0], QUOTE_CHARS))}"
                        + (f" ({_n_sessions_of(found, 'use_instead', use[0][0], _root_name)})")
                    )
                if out:
                    parts.append(
                        f"not {code(q(out[0][0], QUOTE_CHARS))}"
                        + (f" ({_n_sessions_of(found, 'ruled_out', out[0][0])})")
                    )
                detail += " The rule, as they put it: " + ", ".join(parts) + "."
                line = ", ".join(
                    [
                        *([f"use {code(q(use[0][0], QUOTE_CHARS))}"] if use else []),
                        *(
                            [("not " if use else "do not use ") + code(q(out[0][0], QUOTE_CHARS))]
                            if out
                            else []
                        ),
                    ]
                )
                paste["agents_md"] = f"in {code(self.key)}: {line}." if self.key else f"{line}."
        self.add(
            "write-down-the-rule",
            "Write down the rule the human keeps repeating"
            if repeated
            else (
                "Check whether this correction is a standing rule"
                if len(found) == 1
                else "Check whether these corrections are standing rules"
            ),
            detail,
            [signals.USER_CORRECTION],
            self._rule_written(found, said),
            paste=paste,
        )
        self._claimed_done(found)

    def _claimed_done(self, found: Sequence[Finding]) -> None:
        """The agent said the work was done; the human then found it does not work."""
        claimed = [f for f in found if f.detail.get("claimed_done")]
        if not claimed:
            return
        checks = _top([f.detail.get("checked_with", "") for f in claimed], 1)
        check = (
            f" The last check it ran and saw pass was {code(checks[0][0])}: it did not "
            "cover what broke."
            if checks and self.quote is not None
            else ""
        )
        where = "work here" if self.key else "this work"
        self.add(
            "say-how-to-verify",
            "Say how to check work here before calling it done",
            f"The agent said the work was done {_times(len(claimed))} "
            f"({_n(_sessions(claimed), 'session')}), and the human then found it does not "
            f"work.{check} Say in AGENTS.md how to check {where} before reporting it done "
            "(the command, the environment it must pass in, what to compare), and have the "
            "agent say what it did not verify.",
            [signals.USER_CORRECTION],
            events=len(claimed),
            stated=True,
            paste=(
                {
                    "agents_md": (f"in {code(self.key)}: " if self.key else "")
                    + "before saying the work is done, check it the way a human will"
                    + (f" (passing {code(checks[0][0])} was not enough here)" if checks else "")
                    + ", and say what you did not verify."
                }
                if self.quote is not None
                else {}
            ),
        )

    def _rule_written(self, found: Sequence[Finding], said: str) -> Already | None:
        """The "already written down" form: the files name what the human named.

        A correction that names `PaymentClient` in a repository whose AGENTS.md has a
        line about `PaymentClient` is most likely that line being overlooked, and one
        more line would be overlooked the same way.
        """
        names: list[str] = []
        # The file itself being named there is the ordinary "also mentioned" note.
        own = {part for subject in self.subjects for part in (subject, subject.rsplit("/", 1)[-1])}
        for finding in found:
            for name in _NAME_RE.findall(finding.detail.get("quote", "")):
                if name not in names and name not in own and name.rsplit("/", 1)[-1] not in own:
                    names.append(name)
        if not names:
            return None
        about = ""
        if self.quote is not None:
            shown = [code(self.quote(name, QUOTE_CHARS)) for name in names[:MAX_QUOTES]]
            about = f" ({_and(shown)})"
        return (
            names,
            "The rule seems to be written down already: make it harder to miss",
            f"says something about what the human corrected here {_in_sessions(found)}"
            f"{about}. If that is this rule, it is written down and still not followed: "
            "make it more prominent or move it closer to the code (a nested AGENTS.md, a "
            "comment at the top of the file), or enforce it with a hook or a check, rather "
            f"than adding another line.{said}",
        )

    def rejections(self) -> None:
        found = self.get(signals.TOOL_REJECTED)
        reasons = [f.detail.get("reason", "") for f in found if f.detail.get("reason")]
        if len(found) < MIN_EVENTS and not reasons:
            return
        detail = (
            f"A human declined the agent's action {_in_sessions(found)}. State the boundary "
            "explicitly (what must not be touched or run, and what to do instead) in "
            "AGENTS.md, or encode it as a permission rule."
        )
        if self.quote is not None and reasons:
            detail += " Reasons given: " + " / ".join(
                f'"{self.quote(r, QUOTE_CHARS)}"' for r, _ in _top(reasons)
            )
        self.add(
            "state-the-boundary",
            "State the boundary",
            detail,
            [signals.TOOL_REJECTED],
            events=len(found),
            stated=bool(reasons),
            paste=self._boundary_paste(found),
        )

    def _boundary_paste(self, found: Sequence[Finding]) -> dict[str, str]:
        """The line and the deny rule for a declined command, ready to paste: only where a
        human said why in words that forbid it ("never delete ..."), and only with
        excerpts on (the line quotes them)."""
        if self.quote is None:
            return {}
        for finding in found:
            reason = finding.detail.get("reason", "")
            step = _declined_step(finding.detail.get("command", ""), self.subjects)
            if step and _FORBIDS_RE.search(reason) and not _DEFERS_RE.search(reason):
                said = self.quote(reason.strip().rstrip("."), QUOTE_CHARS)
                return {
                    "agents_md": f"never run {code(step)}: {said}.",
                    "deny": f"Bash({step}:*)",
                }
        return {}

    def interrupts(self) -> None:
        found = self.get(signals.USER_INTERRUPT)
        if len(found) < MIN_EVENTS:
            return
        self.add(
            "clarify-before-acting",
            "Tell agents what to check before acting here",
            f"Humans interrupted agents working here {_in_sessions(found)}. Open the cited "
            "transcript lines to see what was being attempted, then document the expected "
            "approach or the precondition that was missed.",
            [signals.USER_INTERRUPT],
        )

    def no_convergence(self, key: str | None) -> None:
        """``key`` is the command for a command hotspot, ``None`` for a file."""
        found = self.get(signals.NO_CONVERGENCE)
        if len(found) < MIN_EVENTS:
            return
        rounds = max(int(f.detail.get("count", "0")) for f in found)
        if key is not None:
            title = f"Agents cannot get {code(key)} to pass"
            opening = f"Agents edited and re-ran {code(key)}"
        else:
            commands = _top([_command_key(f) for f in found], 2)
            names = " / ".join(f"{code(name)}" for name, _ in commands) or "the check"
            title = "Edits here do not get the check to pass"
            opening = f"Agents edited this file and re-ran {names}"
        self.add(
            "explain-the-failing-check",
            title,
            f"{opening} up to {rounds} times in a row without it ever going green "
            f"({_in_sessions(found)}). The failure output did not lead them to a fix. "
            "Document in AGENTS.md how to run and debug this check (one test at a time, "
            "where its fixtures and expected values come from) and what behaviour it "
            "expects, or make its failure message say so.",
            [signals.NO_CONVERGENCE],
        )

    def search_misses(self, where: str) -> None:
        # A search for leftovers (`TODO`, `console.log`) that finds none needs no pointer.
        found = [f for f in self.get(signals.SEARCH_MISS) if "hygiene" not in f.detail]
        if len(found) < MIN_EVENTS:
            return
        detail = f"Agents searched {where} and found nothing {_in_sessions(found)}."
        if self.quote is not None:
            patterns = _top([f.detail.get("pattern", "") for f in found])
            if patterns:
                detail += f" They looked for {_code_list(patterns, self.quote)}."
        detail += (
            " If the concept exists under another name or elsewhere, add a pointer in "
            "AGENTS.md (or a comment/alias where agents look). If it does not exist, say so."
        )
        self.add(
            "add-a-pointer",
            "Point agents to what they are searching for",
            detail,
            [signals.SEARCH_MISS],
        )

    # ---- file rules ------------------------------------------------------------------

    def standing_test(self, when: str, command: bool = False) -> bool:
        """The same test is red in session after session and nothing makes it pass.

        The advice is given once: on the test's file where the failure is attributed
        to one, and on the command only for a test that has no file in the repository.
        """
        known = [f for f in self.get(signals.COMMAND_FAILURE) if f.detail.get("standing_test")]
        if not known:
            return False
        if command:
            known = [f for f in known if not any(t.kind == model.FILE for t in f.targets)]
            if not known:
                return True  # said on the file's row; nothing more to say here
        tests = _top([f.detail["standing_test"] for f in known], 3)
        if self.quote is not None:
            named = _and([code(self.quote(test, QUOTE_CHARS)) for test, _ in tests])
            title = f"{code(self.quote(tests[0][0], QUOTE_CHARS))} is red session after session"
        else:
            named = "The same test" if len(tests) == 1 else "The same tests"
            title = "The same test is red session after session"
        self.add(
            "say-if-it-is-known-broken",
            title,
            f"{named} failed {when} ({_in_sessions(known)}), and nothing in those sessions "
            "made it pass. Fix it, or mark it as a known failure (skip, xfail) and say so in "
            "AGENTS.md, so that agents neither chase it nor learn to ignore a red run.",
            [signals.COMMAND_FAILURE],
        )
        return True

    def file(self, facts: FileFacts | None) -> None:
        self.standing_test("in this file")
        misses = self.get(signals.EDIT_MISS)
        ambiguous = self.get(signals.EDIT_MISS, "ambiguous")
        stale = self.get(signals.STALE_EDIT)
        # A sitting of many edits that ended on a green command did converge.
        thrash = [f for f in self.get(signals.EDIT_THRASH) if not f.detail.get("ended_green")]
        reverts = self.get(signals.EDIT_REVERT)
        too_large = self.get(signals.FILE_TOO_LARGE)
        rework = self.get(signals.HUMAN_REWORK)
        generated = facts is not None and facts.generated
        large = facts is not None and facts.lines is not None and facts.lines >= LARGE_FILE_LINES

        # Only what a transcript shows: a human bumping a lockfile after an agent commit
        # says nothing about anybody having had trouble with the file.
        # A correction alone is enough to fire; the count is of edits that went wrong.
        involved = [*misses, *stale, *reverts] or self.get(signals.USER_CORRECTION)
        if generated and facts is not None and involved:
            sure = facts.generated_by == GENERATED_BY_HEADER
            self.add(
                "edit-the-source-not-the-output",
                "Generated file: point agents at its source"
                if sure
                else "Possibly a generated file: if so, point agents at its source",
                (
                    "This file says it is generated (it starts with a generated-file header)"
                    if sure
                    else f"This file may be generated (judging only by {facts.generated_reason}; "
                    "it carries no generated-file header, so check)"
                )
                + f", yet agents ran into trouble editing it directly {_in_sessions(involved)}. "
                + (
                    f"Its header names the fix: say in AGENTS.md "
                    f'"{generated_line(self.key, facts)}", and deny direct edits to it.'
                    if sure and (facts.source or facts.regenerate)
                    else ("Say" if sure else "If it is, say")
                    + " in AGENTS.md which source to change and which command regenerates it, "
                    "and consider denying direct edits to it."
                ),
                [f.signal for f in involved],
                (
                    self.subjects,
                    "Generated file: telling agents was not enough",
                    "has an instruction about this file, yet agents ran into trouble editing "
                    f"it directly {_in_sessions(involved)}. Check that the cited line says not "
                    "to edit it by hand. If it does, another line will not help; the next "
                    "step is to enforce it: deny "
                    "direct edits with a permission rule, or add a pre-edit hook that names "
                    "the source to change and the command that regenerates the file. (If "
                    "that line is newer than these sessions, give it time first.)",
                ),
                paste=(
                    {
                        "agents_md": generated_line(self.key, facts),
                        # a path with glob characters would match other files
                        **(
                            {}
                            if any(c in self.key for c in "*?[]{}!\\")
                            else {"deny": f"Edit(/{self.key})"}
                        ),
                        **({"source": facts.source} if facts.source else {}),
                        **({"regenerate": facts.regenerate} if facts.regenerate else {}),
                    }
                    if sure and self.key
                    else {}
                ),
            )
        if len(misses) >= MIN_EVENTS and large and facts is not None:
            self.add(
                "split-or-anchor-large-file",
                "Large file: split it or add unique anchors",
                f"{_n(len(misses), 'edit')} failed to locate the target in this {facts.lines}-line "
                f"file ({len(ambiguous)} matched several places, "
                f"{len(misses) - len(ambiguous)} matched nothing) across "
                f"{_n(_sessions(misses), 'session')}. Split it into smaller modules, or give "
                "repeated blocks unique nearby text (section comments, distinct names) so "
                "an edit can be targeted.",
                [signals.EDIT_MISS],
            )
        elif len(too_large) >= MIN_EVENTS and not generated:
            # The file as it is now may be small (it was split since, or its few lines
            # are very long): a line count that argues against "too large" is left out.
            lines = facts.lines if facts is not None and facts.lines else 0
            size = f" ({_n(lines, 'line')})" if lines >= LARGE_FILE_LINES else ""
            self.add(
                "split-or-anchor-large-file",
                "Large file: agents cannot read it in one piece",
                f"Reads of this file{size} were refused as too large {_in_sessions(too_large)}"
                ", so agents page through it or search it blind. Split it, or say in "
                "AGENTS.md which parts matter and how to find them (section names to search "
                "for).",
                [signals.FILE_TOO_LARGE],
            )
        rewritten = [f for f in misses if f.detail.get("rewritten")]
        if len(misses) >= MIN_EVENTS and not generated and not large:
            if len(ambiguous) * 2 >= len(misses):
                detail = (
                    f"{len(ambiguous)} of {len(misses)} failed edits matched several places: "
                    "the file contains repeated blocks. Give them distinguishing text or "
                    "factor the repetition out."
                )
                title = "Repeated blocks: make edit targets unique"
            elif rewritten or self.get(signals.STALE_EDIT, "modified"):
                seen = (
                    f"Before {_n(len(rewritten), 'of them', 'of them')} a command that "
                    "rewrites files (a formatter, a fixer, a commit hook) had run since the "
                    "agent last read the file. "
                    if rewritten
                    else "Writes to it were also refused because it had changed on disk. "
                )
                detail = (
                    f"{_n(len(misses), 'edit')} in {_n(_sessions(misses), 'session')} did not "
                    f"find the text the agent expected. {seen}Document the formatting step, "
                    "or run it in a hook so the agent sees the result before it edits again."
                )
                title = "Agents misremember this file: check what rewrites it"
            else:
                # "More than the rest of the repository" needs a rest to compare with.
                compared = (
                    ". Too little else was edited here to compare against; it is reported "
                    f"because it is well above the {scoring.BASELINE_FLOOR:.0%} taken as "
                    "ordinary. "
                    if any(f.detail.get(scoring.NO_COMPARISON) for f in misses)
                    else ", clearly more often than in the rest of this repository. "
                )
                detail = (
                    f"{_n(len(misses), 'edit')} in {_n(_sessions(misses), 'session')} did not "
                    f"find the text the agent expected{compared}"
                    "Nothing in the transcripts shows the file being "
                    "rewritten in between, so look at what makes its text hard to reproduce "
                    "exactly (tabs, CRLF line endings, long or near-identical lines) and at "
                    "whether agents edit it long after reading it."
                )
                title = "Edits to this file keep missing their target"
            self.add("make-edits-land", title, detail, [signals.EDIT_MISS])

        modified = self.get(signals.STALE_EDIT, "modified")
        if len(modified) >= MIN_EVENTS and not generated:
            self.add(
                "document-what-rewrites-this-file",
                "Something rewrites this file between read and write",
                f"Writes were refused {_in_sessions(modified)} because the file changed on "
                "disk after the agent read it. Find the writer (formatter on save, watcher, "
                "code generator, a parallel agent) and document it, or make it run "
                "deterministically at a known point.",
                [signals.STALE_EDIT],
            )

        path_misses = self.get(signals.PATH_MISS)
        if len(path_misses) >= MIN_EVENTS:
            self.add(
                "path-agents-expect",
                "Agents expect this path to exist",
                (
                    "Agents tried to `cd` into this non-existent directory "
                    if all(f.detail.get("variant") == "directory" for f in path_misses)
                    else "Agents tried to open this non-existent path "
                )
                + f"{_in_sessions(path_misses)}. "
                + "Add a line to AGENTS.md saying where this actually lives, or create the "
                "file/alias if the guess is the more natural layout.",
                [signals.PATH_MISS],
            )

        self.corrections()
        self.rejections()
        self.denials("to change this file")
        self.interrupts()

        # Thrash in a turn that ran a check was not for want of one, and where the check
        # itself would not pass, `explain-the-failing-check` says what is needed.
        blind = [f for f in thrash if not f.detail.get("checked")]
        stuck = len(self.get(signals.NO_CONVERGENCE)) >= MIN_EVENTS
        # A change that was tried, checked and then taken back was not made blind either:
        # the check did its job. What the agent lacked was the rule the change broke.
        tested = [f for f in reverts if f.detail.get("checked")]
        untested = [f for f in reverts if not f.detail.get("checked")]
        if len(blind) + len(untested) < MIN_EVENTS and len(reverts) >= MIN_EVENTS and not stuck:
            self.add(
                "state-the-constraint",
                "Say what must not change in this file",
                f"Agents made a change here and backed it out {_times(len(reverts))} in "
                f"{_n(_sessions(reverts), 'session')}, {len(tested)} of them after a test, "
                "lint or build command had run on it. A check exists and was used, so the "
                "agents were not iterating blind: they tried something this file does not "
                "allow. State the constraint in AGENTS.md or in a comment at the top of "
                "the file, so the next agent does not try the same thing.",
                [signals.EDIT_REVERT],
            )
        reverts = untested
        if len(blind) + len(reverts) >= MIN_EVENTS and not stuck:
            thrash = blind
            parts = [
                _n(len(thrash), "thrash episode") if thrash else "",
                _n(len(reverts), "reverted edit") if reverts else "",
            ]
            self.add(
                "add-a-fast-check",
                "Give agents a fast way to check changes to this file",
                f"Edits here did not converge: {' and '.join(p for p in parts if p)} in "
                f"{_n(_sessions([*thrash, *reverts]), 'session')}. Document the quickest "
                "command that validates this file (a single test, a type check) so agents "
                "can verify instead of iterating blind.",
                [f.signal for f in (*thrash, *reverts)],
            )

        if len(rework) >= MIN_EVENTS:
            detail = (
                f"Humans changed this file again shortly after {len(rework)} agent commits "
                f"touched it ({_sessions(rework)} distinct agent commits)."
            )
            shas = sorted({f.detail.get("human_commit", "") for f in rework} - {""})
            detail += f" Follow-up commits: {', '.join(shas[:MAX_QUOTES])}."
            detail += (
                " Read those follow-ups: whatever they fix repeatedly is a convention to "
                "document or a test to add."
            )
            self.add(
                "learn-from-rework",
                "Learn from the human follow-ups",
                detail,
                [signals.HUMAN_REWORK],
            )

        self.search_misses("this file")
        self.no_convergence(None)

        loops = self.get(signals.READ_LOOP)
        if len(loops) >= MIN_EVENTS:
            size = f" ({_n(facts.lines, 'line')})" if facts is not None and facts.lines else ""
            self.add(
                "summarize-this-file",
                "Agents keep re-reading this file",
                f"The same part of this file{size} was re-read without progress "
                f"{_in_sessions(loops)}. A short header comment or AGENTS.md note on what "
                "it contains and where the important parts are would save the round trips.",
                [signals.READ_LOOP],
            )

    def guardrail(self, what: str) -> None:
        """A hook or a deny rule refused the call and the agent went another way."""
        held = [f for f in self.get(signals.PERMISSION_DENIED) if scoring.is_guardrail_hit(f)]
        if len(held) < MIN_EVENTS:
            return
        hooks = sum(f.detail.get("deliberate") == "hook" for f in held)
        by = "a hook" if hooks * 2 > len(held) else "a deny rule in the settings"
        ways = _top([f.detail["alternative"] for f in held if f.detail.get("alternative")])
        went = (
            f"and each time the agent went on without it ({_times(ways[0][1])} with "
            f"{code(ways[0][0])})"
            if ways
            else "and each time the agent went on without retrying it"
        )
        reasons = _top([f.detail["hook_said"] for f in held if f.detail.get("hook_said")])
        said = (
            f' The hook says: "{self.quote(reasons[0][0], QUOTE_CHARS)}".'
            if reasons and self.quote is not None
            else ""
        )
        # where agents could have read it before trying
        terms = [_bare(ways[0][0])] if ways else list(self.subjects)
        written = self.guidance.mentions(terms, self.near) if self.guidance is not None else []
        written = [m for m in written if m.file not in SETTINGS_FILES]
        tell = code(_bare(ways[0][0])) if ways else "what to do instead"
        if written:
            closing = (
                f"Nothing needs fixing: {_refs(written)} already names "
                f"{tell if ways else 'it'}, and the refusal costs one round trip. If that "
                "is too many, move that line to where agents read first."
            )
        else:
            closing = (
                "Nothing needs fixing in the guardrail. To save the round trip, say in "
                f"AGENTS.md that this is refused and to use {tell}."
                if ways
                else "Nothing needs fixing in the guardrail. To save the round trip, say in "
                "AGENTS.md that this is refused and what to do instead."
            )
        first = "try to change this file" if what.startswith("to ") else f"try {what} first"
        self.add(
            "the-guardrail-works",
            f"The guardrail works; agents still {first}",
            f"Agents tried {what} {_in_sessions(held)} and were refused by {by} before "
            f"anything ran, {went}.{said} {closing}",
            [signals.PERMISSION_DENIED],
            events=len(held),
        )
        if ways:
            self.out[-1]["replacement"] = ways[0][0]
        if written:
            self.out[-1]["documented_in"] = [m.as_dict() for m in written]
            self.out[-1]["documented_as"] = "instruction" if ways else "mention"

    def denials(self, what: str) -> None:
        self.guardrail(what)
        denied = [f for f in self.get(signals.PERMISSION_DENIED) if not scoring.is_guardrail_hit(f)]
        if len(denied) < MIN_EVENTS:
            return
        hooks = sum(f.detail.get("variant") == "hook" for f in denied)
        blocked = sum(f.detail.get("variant") == "blocked" for f in denied)
        if blocked * 2 > len(denied):
            # Claude Code refuses some forms by itself ("Blocked: sleep 100 followed by:
            # ..."): a rule of the agent tool, the same in every repository. Nothing here
            # caused it and no setting of this repository changes it.
            instead = _top([_harness_instead(f.excerpt) for f in denied])
            says = (
                f' Its message says what to do instead: "{self.quote(instead[0][0], QUOTE_CHARS)}"'
                if instead and self.quote is not None
                else " Its message says what to do instead (see the cited lines)."
            )
            self.add(
                "allow-or-document-the-boundary",
                f"Built into the agent tool, not this repository: agents keep trying {what}",
                f"Agents tried {what} {_in_sessions(denied)} in a form the agent tool itself "
                "refuses to run: a built-in rule of the harness (Claude Code), not a hook, "
                f"a permission setting or anything in this repository.{says} Nothing in the "
                "repository needs to change. If the round trips cost too much, one line in "
                "AGENTS.md (or CLAUDE.md) with that alternative makes the first attempt the "
                "right one.",
                [signals.PERMISSION_DENIED],
                events=len(denied),
                origin="agent-tool",
            )
            return
        automatic = sum(f.detail.get("variant") in ("classifier", "safety") for f in denied)
        if automatic * 2 > len(denied):
            self.add(
                "allow-or-document-the-boundary",
                "Tell agents this is refused, and what to do instead",
                f"Agents tried {what} {_in_sessions(denied)} and were refused by the "
                "harness's auto-mode classifier or a built-in safety check before anything "
                "ran. A permission rule does not change that. Say in AGENTS.md that this is "
                "not available to agents and what to do instead (a narrower command, or "
                "stop and ask).",
                [signals.PERMISSION_DENIED],
                events=len(denied),
                origin="agent-tool",
            )
            return
        by = "a hook" if hooks * 2 > len(denied) else "permission settings"
        deliberate = sum("deliberate" in f.detail for f in denied)
        if deliberate * 2 > len(denied):
            # A hook or a deny rule is there on purpose: an allow rule does not override
            # a hook, and would contradict the rule.
            by = "a hook" if hooks * 2 > len(denied) else "a deny rule in the settings"
            around = sum("got_through" in f.detail for f in denied)
            if around * 2 > len(denied):
                self.add(
                    "allow-or-document-the-boundary",
                    "Tell agents this is off limits, or close the way around",
                    f"Agents tried {what} {_in_sessions(denied)} and were refused by {by} "
                    "before anything ran, and then got the same thing done anyway (the same "
                    "command in another form, or the same file by another tool). If it is "
                    "meant to be off limits, say so in AGENTS.md together with what to do "
                    "instead, and check that the guardrail covers the form that got "
                    "through; if it is fine, narrow the guardrail so the first attempt is "
                    "not refused.",
                    [signals.PERMISSION_DENIED],
                    events=len(denied),
                )
            else:
                self.add(
                    "allow-or-document-the-boundary",
                    "Tell agents this is off limits, and what to do instead",
                    f"Agents tried {what} {_in_sessions(denied)} and were refused by {by} "
                    "before anything ran; the sessions end there, so no other way was "
                    "seen. The guardrail is there on purpose: say in AGENTS.md that this "
                    "is refused and what to do instead, or have the refusal itself say it.",
                    [signals.PERMISSION_DENIED],
                    events=len(denied),
                )
            return
        self.add(
            "allow-or-document-the-boundary",
            "Allow it, or tell agents it is off limits",
            f"Agents tried {what} {_in_sessions(denied)} and were refused by {by} before "
            "anything ran. If this is routine and safe, add an allow rule so they stop "
            "stalling on it; if it is meant to be off limits, say so in AGENTS.md together "
            "with what to do instead.",
            [signals.PERMISSION_DENIED],
            events=len(denied),
        )

