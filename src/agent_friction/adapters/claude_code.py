"""Adapter for Claude Code session transcripts (``~/.claude/projects/**.jsonl``)."""

from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from typing import Any

from agent_friction import model
from agent_friction.adapters import common
from agent_friction.model import Event, ParsedFile, Stream

KIND = "claude-code"

INTERRUPT_PREFIX = "[Request interrupted by user"

#: User-role text that is produced by the harness, not typed by the human.
WRAPPER_PREFIXES = (
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<local-command-caveat>",
    "<system-reminder>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<user-prompt-submit-hook>",
    "<task-notification>",
    "<user-memory-input>",
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",
)
#: Slash commands start a new human turn but are never read as corrections.
COMMAND_PREFIXES = ("<command-name>", "<command-message>", "<command-args>")

#: Blocks the harness or an IDE extension puts into user turns. They are removed before a
#: prompt is read, quoted or attributed: none of it was typed by the human.
_HARNESS_TAGS = (
    r"system-reminder|ide_opened_file|ide_selection|ide_diagnostics|ide_[a-z_]+"
    r"|local-command-[a-z]+|user-prompt-submit-hook|command-stdout|command-stderr"
    r"|bash-input|bash-stdout|bash-stderr|task-notification|user-memory-input|post-tool-use-hook"
    r"|system-note|session-context|tools-used-before-summary"
)
#: Envelopes around what *another agent* wrote into a user turn (a teammate in a team, a
#: coordinating or peer session). It starts a turn like a prompt does, but nobody typed
#: it: it is never a correction, is never quoted, and the tag is not text.
_PEER_RE = re.compile(
    r"<((?:teammate|agent|peer|coordinator)-message)\b[^>]*>.*?(?:</\1>|\Z)", re.S
)
_REMINDER_RE = re.compile(rf"<({_HARNESS_TAGS})\b[^>]*>.*?</\1>", re.S)

_TOOL_OPS = {
    "Read": model.OP_READ,
    "NotebookRead": model.OP_READ,
    "Edit": model.OP_EDIT,
    "MultiEdit": model.OP_EDIT,
    "NotebookEdit": model.OP_EDIT,
    "Write": model.OP_WRITE,
    "Bash": model.OP_SHELL,
    "PowerShell": model.OP_SHELL,  # Claude Code on Windows
    "Shell": model.OP_SHELL,
    "Grep": model.OP_SEARCH,
    "Glob": model.OP_SEARCH,
}


#: Tools that ask about, or stop, a command running in the background.
_TASK_TOOLS = frozenset({"BashOutput", "TaskOutput", "KillShell", "KillBash", "TaskStop"})
_LAUNCHED_RE = re.compile(r"\s*Command (?:is )?running in (?:the )?background with ID: ([\w.-]+)")
_NOTIFICATION_RE = re.compile(r"<task-notification>(.*?)</task-notification>", re.S)
_STATUS_RE = re.compile(r"<status>\s*([\w-]+)\s*</status>")
_EXIT_CODE_RE = re.compile(r"<exit_code>\s*(-?\d+)\s*</exit_code>|\bexit code (\d+)\b")
_TASK_ID_RE = re.compile(r"<(?:task-id|task_id|tool-use-id)>\s*([^<\s]+)\s*</")
_OUTPUT_RE = re.compile(r"<(stdout|stderr|output)>(.*?)</\1>", re.S)


def _str(value: object) -> str | None:
    return value if isinstance(value, str) and value else None


def session_id_for(path: Path) -> str:
    """The session a transcript file belongs to.

    ``<id>.jsonl`` is session ``<id>``; ``<id>/subagents/*.jsonl`` belongs to its
    parent session, so subagent friction does not inflate the session count.
    """
    if path.parent.name == "subagents" and path.parent.parent.name:
        return path.parent.parent.name
    return path.stem


def _flatten(content: object) -> str:
    """Text of a tool_result ``content`` (string or list of blocks). Never thinking."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = [
            block["text"]
            for block in content
            if isinstance(block, dict)
            and block.get("type") == "text"
            and isinstance(block.get("text"), str)
        ]
        return "\n".join(parts)
    return ""


def _tool_call(block: dict[str, Any], line: int, base: dict[str, Any]) -> Event | None:
    call_id = _str(block.get("id"))
    name = _str(block.get("name"))
    if call_id is None or name is None:
        return None
    raw_input = block.get("input")
    inp: dict[str, Any] = raw_input if isinstance(raw_input, dict) else {}
    event = Event(
        kind=model.TOOL_CALL,
        line=line,
        call_id=call_id,
        tool=name,
        op=_TOOL_OPS.get(name, model.OP_OTHER),
        **base,
    )
    if event.op in (model.OP_READ, model.OP_EDIT, model.OP_WRITE):
        event.path = _str(inp.get("file_path")) or _str(inp.get("notebook_path"))
    if event.op == model.OP_READ:
        event.read_range = f"{inp.get('offset', '')}:{inp.get('limit', '')}"
    elif name == "Edit":
        old, new = inp.get("old_string"), inp.get("new_string")
        if isinstance(old, str) and isinstance(new, str):
            event.edits, event.insertions = common.edit_pairs([(old, new)])
            event.new_text = common.new_text(new)
            event.old_text = common.new_text(old)
    elif name == "MultiEdit":
        edits = inp.get("edits")
        if isinstance(edits, list):
            event.edits, event.insertions = common.edit_pairs(
                [
                    (e["old_string"], e["new_string"])
                    for e in edits
                    if isinstance(e, dict)
                    and isinstance(e.get("old_string"), str)
                    and isinstance(e.get("new_string"), str)
                ]
            )
            event.new_text = common.new_text(
                *(e.get("new_string") for e in edits if isinstance(e, dict))
            )
            event.old_text = common.new_text(
                *(e.get("old_string") for e in edits if isinstance(e, dict))
            )
    elif name == "Write":
        content = inp.get("content")
        if isinstance(content, str):
            event.content_digest = common.digest(content)
            event.new_text = common.new_text(content)
    elif event.op == model.OP_SHELL:
        event.command = _str(inp.get("command"))
        event.background = inp.get("run_in_background") is True
    elif name in _TASK_TOOLS:
        # BashOutput / TaskOutput / KillShell: which background task this asks about
        for field in ("bash_id", "task_id", "shell_id"):
            event.task_id = event.task_id or (_str(inp.get(field)) or "")
    elif event.op == model.OP_SEARCH:
        event.pattern = _str(inp.get("pattern"))
        event.path = _str(inp.get("path"))
    return event


def _tool_result(
    block: dict[str, Any], structured: object, line: int, base: dict[str, Any]
) -> Event | None:
    call_id = _str(block.get("tool_use_id"))
    if call_id is None:
        return None
    text = _flatten(block.get("content"))
    event = Event(kind=model.TOOL_RESULT, line=line, call_id=call_id, **base)
    # Trust the flag. The error tag only counts when the result starts with it:
    # a successful command may well print "<tool_use_error>" (e.g. from a test file).
    tagged = text.lstrip().startswith("<tool_use_error>")
    is_error = block.get("is_error") is True or tagged
    event.harness_error = tagged
    clean = common.strip_error_tags(text) if is_error else text.strip()
    info: dict[str, Any] = structured if isinstance(structured, dict) else {}
    reason = common.rejection_reason(text)
    denied = common.denial(text) if is_error else None
    if reason is not None:
        event.ok, event.error, event.reason = False, model.ERR_REJECTED, reason
    elif denied is not None:
        event.ok, event.error, event.reason = False, model.ERR_DENIED, denied
    elif clean.startswith(INTERRUPT_PREFIX) or info.get("interrupted") is True:
        event.ok, event.error = False, model.ERR_INTERRUPTED
    else:
        code = common.exit_code(clean)
        if code is not None:
            event.exit_code = code
        if is_error:
            event.ok = False
            event.error, event.matches = common.classify_error(clean)
            if code is not None:
                event.error = model.ERR_EXIT
        elif code:
            event.ok, event.error = False, model.ERR_EXIT
    if event.ok:
        event.empty = common.is_empty_search(clean) or (
            info.get("numFiles") == 0 and not info.get("numMatches")
        )
    event.output = common.clip_output(clean)
    started = _LAUNCHED_RE.match(clean)
    task = info.get("backgroundTaskId")
    if started is not None or (isinstance(task, str) and task):
        # "Command running in background with ID: ...": the launch, not the outcome
        event.background = True
        event.task_id = task if isinstance(task, str) and task else started.group(1)  # type: ignore[union-attr]
    return event


def _outcome(text: str, line: int, base: dict[str, Any], call_id: str = "") -> Event | None:
    """How a background task ended, from a poll's result or a ``<task-notification>``."""
    status = _STATUS_RE.search(text)
    if status is None:
        return None
    event = Event(kind=model.BACKGROUND_OUTCOME, line=line, call_id=call_id, **base)
    event.task_status = status.group(1).lower()
    code = _EXIT_CODE_RE.search(text)
    if code is not None:
        event.exit_code = int(code.group(1) or code.group(2))
    task = _TASK_ID_RE.search(text)
    if task is not None:
        event.task_id = task.group(1).strip()
    parts = [body.strip() for _, body in _OUTPUT_RE.findall(text) if body.strip()]
    event.output = common.clip_output("\n".join(parts))
    return event


def _user_text(text: str, line: int, base: dict[str, Any]) -> Event | None:
    stripped = _REMINDER_RE.sub("", text).strip()
    from_peer = _PEER_RE.search(stripped) is not None
    stripped = _PEER_RE.sub("", stripped).strip()
    if not stripped:
        # another agent's message alone: a new turn, with no human words in it
        return (
            Event(kind=model.USER_MESSAGE, line=line, synthetic=True, **base) if from_peer else None
        )
    if stripped.startswith(INTERRUPT_PREFIX):
        return Event(kind=model.INTERRUPT, line=line, text=stripped, **base)
    if stripped.startswith(COMMAND_PREFIXES):
        return Event(kind=model.USER_MESSAGE, line=line, synthetic=True, **base)
    if stripped.startswith(WRAPPER_PREFIXES) or common.HOOK_FEEDBACK_RE.match(stripped):
        return None
    return Event(kind=model.USER_MESSAGE, line=line, text=stripped, **base)


def _prompted(decision: object) -> bool | None:
    """Was the call approved by a person? From the line's ``permissionDecision``.

    ``{"decision": "accept", "source": "config"}`` is the permission settings (or
    the mode, or a hook) deciding at once. Any other source is somebody answering
    a prompt. ``None`` when the line carries no decision.
    """
    if not isinstance(decision, dict) or not isinstance(decision.get("source"), str):
        return None
    return bool(decision["source"].casefold() != "config")


def _line_events(obj: dict[str, Any], line: int) -> list[Event] | None:
    """Events for one transcript line, or ``None`` if the line is structurally invalid."""
    message = obj.get("message")
    if not isinstance(message, dict):
        return None
    content = message.get("content")
    base: dict[str, Any] = {
        "ts": common.parse_ts(obj.get("timestamp")),
        "cwd": _str(obj.get("cwd")),
    }
    events: list[Event] = []
    if obj["type"] == "assistant":
        if isinstance(content, list):
            for block in content:
                if isinstance(block, dict) and block.get("type") == "tool_use":
                    call = _tool_call(block, line, base)
                    if call is not None:
                        events.append(call)
        if not events and isinstance(content, (str, list)):
            # Prose or thinking: only the fact that the agent was active at this time.
            events.append(Event(kind=model.AGENT_MESSAGE, line=line, **base))
        return events
    human = not (obj.get("isMeta") is True or obj.get("isCompactSummary") is True)
    if isinstance(content, str):
        if human:
            event = _user_text(content, line, base)
            if event is not None:
                events.append(event)
        for notice in _NOTIFICATION_RE.findall(content):
            ended = _outcome(notice, line, base)
            if ended is not None:
                events.append(ended)
        return events
    if not isinstance(content, list):
        return None
    texts: list[str] = []
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "tool_result":
            result = _tool_result(block, obj.get("toolUseResult"), line, base)
            if result is not None:
                result.prompted = _prompted(obj.get("permissionDecision"))
                events.append(result)
                polled = _outcome(_flatten(block.get("content")), line, base, result.call_id)
                if polled is not None and not result.background:
                    events.append(polled)
        elif block.get("type") == "text" and isinstance(block.get("text"), str):
            texts.append(block["text"])
    for notice in _NOTIFICATION_RE.findall("\n".join(texts)):
        ended = _outcome(notice, line, base)
        if ended is not None:
            events.append(ended)
    if human and texts:
        event = _user_text("\n".join(texts), line, base)
        if event is not None:
            events.append(event)
    return events


def _claims_done(content: object) -> bool | None:
    """Whether an assistant message ends by saying the work is done (``None``: no text).

    A tool call after the text means it went on working: no claim stands.
    """
    if isinstance(content, str):
        return common.claims_done(content)
    if not isinstance(content, list):
        return None
    verdict: bool | None = None
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "text" and isinstance(block.get("text"), str):
            verdict = common.claims_done(block["text"])
        elif block.get("type") == "tool_use":
            verdict = False
    return verdict


def _asks_question(content: object) -> bool | None:
    """Whether an assistant message asks the human something (``None``: no say either way).

    Only this one bit is kept from assistant prose; the text itself is discarded.
    """
    if isinstance(content, str):
        return common.asks_question(content)
    if not isinstance(content, list):
        return None
    verdict: bool | None = None
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "text" and isinstance(block.get("text"), str):
            verdict = common.asks_question(block["text"])
        elif block.get("type") == "tool_use":
            # A question/choice tool is a question. Any other tool: it went on working, so
            # whatever it asked was rhetorical.
            verdict = bool(common.QUESTION_TOOL_RE.search(str(block.get("name") or "")))
    return verdict


#: Who a queued message is from, where the transcript says (`origin.kind`). Anything
#: else (a task notification, a coordinator, a peer agent, a reminder) is not a human.
_HUMAN_ORIGINS = frozenset({"user", "human"})
#: A queued message and a user line with the same text this close together are one message.
REPLAY_SECONDS = 600.0


def _queued(obj: dict[str, Any]) -> dict[str, Any] | None:
    """The user line a ``queued_command`` attachment stands for, or ``None``.

    What is typed while the agent is working is not a ``user`` line: it is recorded as
    ``{"type": "attachment", "attachment": {"type": "queued_command", "prompt": ...}}``
    at the moment it reaches the agent, with the prompt as a string or as content
    blocks. The same record carries what the harness and other agents queue (task
    notifications, reminders, messages from a coordinator or a peer): those are
    marked by ``origin``, ``commandMode`` or ``isMeta``, and are kept as a
    non-human line, so that a task notification is still read as an outcome.
    """
    attachment = obj.get("attachment")
    if obj.get("type") != "attachment" or not isinstance(attachment, dict):
        return None
    if attachment.get("type") != "queued_command":
        return None
    prompt = attachment.get("prompt")
    if not isinstance(prompt, (str, list)):
        return None
    origin = attachment.get("origin")
    kind = origin.get("kind") if isinstance(origin, dict) else origin
    human = (
        attachment.get("isMeta") is not True
        and obj.get("isMeta") is not True
        and (kind is None or kind in _HUMAN_ORIGINS)
        and attachment.get("commandMode") in (None, "prompt")
    )
    return {
        **obj,
        "type": "user",
        "isMeta": not human,
        "timestamp": obj.get("timestamp") or attachment.get("timestamp"),
        "message": {"role": "user", "content": prompt},
    }


def parse_file(path: Path, seen_uuids: dict[str, str] | None = None) -> ParsedFile:
    """Parse one Claude Code ``.jsonl`` transcript.

    ``seen_uuids`` (line uuid -> session id) de-duplicates lines across files.
    A resumed session replays earlier lines (same ``uuid``) into a new file
    under a new session id: such a file continues the session those lines
    came from and is given its id, so one piece of work is one session.
    """
    seen = seen_uuids if seen_uuids is not None else {}
    resumed_from: str | None = None
    added: list[str] = []
    in_subagent_dir = path.parent.name == "subagents"
    session = session_id_for(path)
    main = Stream(session_id=session, source=path, kind=KIND, sidechain=False)
    side = Stream(session_id=session, source=path, kind=KIND, sidechain=True)
    parsed = ParsedFile(path=path, kind=KIND, streams=[])
    asking = {False: False, True: False}  # per stream: did the agent just ask something?
    claimed = {False: False, True: False}  # ... and did it just say it was done?
    # (stream, text) -> was it a queued one, and when
    delivered: dict[tuple[bool, str], tuple[bool, datetime | None]] = {}
    with model.open_transcript(path) as handle:
        for number, raw in enumerate(handle, 1):
            raw = raw.strip()
            if not raw:
                continue
            try:
                obj = model.load_json_line(raw)
            except (ValueError, RecursionError):
                parsed.skipped_lines += 1
                continue
            if not isinstance(obj, dict):
                parsed.skipped_lines += 1
                continue
            queued = _queued(obj)
            if queued is not None:
                obj = queued  # typed while the agent was working: a user line in all but name
            if obj.get("type") not in ("user", "assistant"):
                parsed.ignored_lines += 1
                continue
            uuid = obj.get("uuid")
            if isinstance(uuid, str) and uuid:
                if uuid in seen:
                    if resumed_from is None and seen[uuid] != session:
                        resumed_from = seen[uuid]
                    parsed.duplicate_lines += 1
                    continue
                seen[uuid] = session
                added.append(uuid)
            events = _line_events(obj, number)
            if events is None:
                parsed.skipped_lines += 1
                continue
            target = side if in_subagent_dir or obj.get("isSidechain") is True else main
            # A message typed mid-turn is recorded when it is delivered and may be
            # recorded again as an ordinary user line: it was said once. The same words
            # typed again much later are a second message.
            for event in [e for e in events if e.kind == model.USER_MESSAGE and e.text]:
                said = (target.sidechain, event.text.strip())
                was_queued, at = delivered.get(said, (queued is not None, None))
                near = (
                    at is None
                    or event.ts is None
                    or abs((event.ts - at).total_seconds()) <= REPLAY_SECONDS
                )
                if said in delivered and (queued is not None) != was_queued and near:
                    del delivered[said]
                    events.remove(event)
                else:
                    delivered[said] = (queued is not None, event.ts)
            if obj["type"] == "assistant":
                asked = _asks_question(obj["message"].get("content"))
                if asked is not None:
                    asking[target.sidechain] = asked
                done = _claims_done(obj["message"].get("content"))
                if done is not None:
                    claimed[target.sidechain] = done
            else:
                for event in events:
                    if event.kind == model.USER_MESSAGE:
                        event.after_question = asking[target.sidechain]
                        asking[target.sidechain] = False
                        event.after_claim = claimed[target.sidechain]
                        claimed[target.sidechain] = False
            target.events.extend(events)
    main.events = common.pair_background(main.events)
    side.events = common.pair_background(side.events)
    if resumed_from is not None and not in_subagent_dir:
        main.session_id = side.session_id = resumed_from
        for uuid in added:
            seen[uuid] = resumed_from
    parsed.streams = [s for s in (main, side) if s.events]
    return parsed
