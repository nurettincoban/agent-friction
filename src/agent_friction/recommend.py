"""Rule-based recommendations.

Each rule looks at the mix of findings on one hotspot and, when its evidence
threshold is met, emits a concrete suggestion that cites the counts (and, when
excerpts are enabled, the actual commands, patterns and human words) behind
it. Rules and thresholds are listed in docs/methodology.md.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from agent_friction import model, signals
from agent_friction.model import Finding

#: A file with at least this many lines is called "large" in recommendations.
LARGE_FILE_LINES = 800
#: Files bigger than this are not opened to count lines or look for markers.
MAX_FACT_BYTES = 5_000_000
#: Bytes inspected at the top of a file for a "generated" marker.
GENERATED_HEAD_BYTES = 2048
#: Events needed before most rules fire (one-off events do not justify a change).
MIN_EVENTS = 2
#: Verbatim quotes / patterns / commands shown per recommendation, at most.
MAX_QUOTES = 3
#: Summed attribution share of corrections needed before "write down the rule" fires.
CORRECTION_MIN_SHARE = 0.5
QUOTE_CHARS = 160

_GENERATED_MARKER_RE = re.compile(
    r"do not edit|don't edit|autogenerated|auto-generated|generated by|@generated"
    r"|code generated|this file (?:is|was) generated",
    re.I,
)
_GENERATED_PATH_RE = re.compile(
    r"(?:^|/)(?:dist|build|out|node_modules|vendor|generated|__generated__|gen)/"
    r"|(?:\.min\.(?:js|css)|_pb2(?:_grpc)?\.pyi?|\.pb\.go|\.g\.dart|\.generated\.[a-z]+"
    r"|[-_.]lock(?:\.json|\.yaml)?|\.lock|\.snap)$"
    r"|(?:^|/)(?:package-lock\.json|pnpm-lock\.yaml|yarn\.lock|poetry\.lock|uv\.lock"
    r"|Cargo\.lock|go\.sum)$"
)

Quoter = Callable[[str, int], str]

#: Every recommendation id this module can emit (documented in docs/methodology.md).
RULE_IDS: tuple[str, ...] = (
    "edit-the-source-not-the-output",
    "split-or-anchor-large-file",
    "make-edits-land",
    "document-what-rewrites-this-file",
    "path-agents-expect",
    "write-down-the-rule",
    "state-the-boundary",
    "clarify-before-acting",
    "add-a-fast-check",
    "learn-from-rework",
    "document-how-to-run",
    "add-a-pointer",
    "summarize-this-file",
    "use-the-working-command",
    "document-the-command",
    "make-the-failure-actionable",
)


@dataclass(frozen=True)
class FileFacts:
    """What we know about a hotspot file from the working tree."""

    exists: bool
    lines: int | None = None
    generated: bool = False
    generated_reason: str = ""

    def as_dict(self) -> dict[str, object]:
        return {"exists": self.exists, "lines": self.lines, "generated": self.generated}


def file_facts(repo: Path, rel: str) -> FileFacts:
    """Inspect ``repo/rel`` (size, generated marker). Never raises."""
    by_path = bool(_GENERATED_PATH_RE.search(rel))
    path = repo / rel
    try:
        if not path.is_file():
            return FileFacts(False, None, by_path, "its path" if by_path else "")
        if path.stat().st_size > MAX_FACT_BYTES:
            return FileFacts(True, None, by_path, "its path" if by_path else "")
        data = path.read_bytes()
    except OSError:
        return FileFacts(False, None, by_path, "its path" if by_path else "")
    lines = data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
    head = data[:GENERATED_HEAD_BYTES].decode("utf-8", "replace")
    marker = _GENERATED_MARKER_RE.search(head)
    if marker:
        return FileFacts(True, lines, True, f'a "{marker.group(0).lower()}" marker')
    return FileFacts(True, lines, by_path, "its path" if by_path else "")


def _sessions(findings: Sequence[Finding]) -> int:
    return len({f.session_id for f in findings})


def _times(count: int) -> str:
    return "once" if count == 1 else f"{count} times"


def _in_sessions(findings: Sequence[Finding]) -> str:
    n = _sessions(findings)
    return f"{_times(len(findings))} in {n} session{'' if n == 1 else 's'}"


def _top(values: Sequence[str], limit: int = MAX_QUOTES) -> list[tuple[str, int]]:
    counts = Counter(v for v in values if v)
    return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:limit]


def _code_list(pairs: Sequence[tuple[str, int]], quote: Quoter) -> str:
    return ", ".join(
        f"`{quote(value, QUOTE_CHARS)}`" + (f" ({count}x)" if count > 1 else "")
        for value, count in pairs
    )


class _Rules:
    def __init__(
        self, findings: Sequence[Finding], quote: Quoter | None, shares: Mapping[int, float]
    ) -> None:
        self.shares = shares
        self.by_signal: dict[str, list[Finding]] = {}
        for finding in findings:
            self.by_signal.setdefault(finding.signal, []).append(finding)
        self.quote = quote
        self.out: list[dict[str, object]] = []

    def get(self, signal: str, variant: str | None = None) -> list[Finding]:
        found = self.by_signal.get(signal, [])
        if variant is None:
            return found
        return [f for f in found if f.detail.get("variant") == variant]

    def add(self, rule_id: str, title: str, detail: str, based_on: Sequence[str]) -> None:
        assert rule_id in RULE_IDS, rule_id
        self.out.append(
            {"id": rule_id, "title": title, "detail": detail, "signals": sorted(set(based_on))}
        )

    # ---- shared rules ----------------------------------------------------------------

    def corrections(self) -> None:
        found = self.get(signals.USER_CORRECTION)
        if sum(self.shares.get(f.fid, 1.0) for f in found) < CORRECTION_MIN_SHARE:
            return  # nothing, or only thin slices of corrections spread over many files
        detail = (
            f"A human corrected the agent here {_in_sessions(found)}. Put the rule in "
            "AGENTS.md / CLAUDE.md (or a comment at the top of the file) so it is read "
            "before the next attempt."
        )
        if self.quote is not None:
            ranked = sorted(found, key=lambda f: (-f.weight, f.source, f.line))
            quotes: list[str] = []
            for finding in ranked:
                text = self.quote(finding.detail.get("quote", ""), QUOTE_CHARS)
                if text and text not in quotes:
                    quotes.append(text)
            if quotes:
                detail += " In their words: " + " / ".join(f'"{q}"' for q in quotes[:MAX_QUOTES])
        self.add(
            "write-down-the-rule",
            "Write down the rule the human keeps repeating",
            detail,
            [signals.USER_CORRECTION],
        )

    def rejections(self) -> None:
        found = self.get(signals.TOOL_REJECTED)
        reasons = [f.detail.get("reason", "") for f in found if f.detail.get("reason")]
        if len(found) < MIN_EVENTS and not reasons:
            return
        detail = (
            f"A human declined the agent's action {_in_sessions(found)}. State the boundary "
            "explicitly (what must not be touched or run, and what to do instead) in "
            "AGENTS.md, or encode it as a permission rule."
        )
        if self.quote is not None and reasons:
            detail += " Reasons given: " + " / ".join(
                f'"{self.quote(r, QUOTE_CHARS)}"' for r, _ in _top(reasons)
            )
        self.add("state-the-boundary", "State the boundary", detail, [signals.TOOL_REJECTED])

    def interrupts(self) -> None:
        found = self.get(signals.USER_INTERRUPT)
        if len(found) < MIN_EVENTS:
            return
        self.add(
            "clarify-before-acting",
            "Tell agents what to check before acting here",
            f"Humans interrupted agents working here {_in_sessions(found)}. Open the cited "
            "transcript lines to see what was being attempted, then document the expected "
            "approach or the precondition that was missed.",
            [signals.USER_INTERRUPT],
        )

    def search_misses(self, where: str) -> None:
        found = self.get(signals.SEARCH_MISS)
        if len(found) < MIN_EVENTS:
            return
        detail = f"Agents searched {where} and found nothing {_in_sessions(found)}."
        if self.quote is not None:
            patterns = _top([f.detail.get("pattern", "") for f in found])
            if patterns:
                detail += f" They looked for {_code_list(patterns, self.quote)}."
        detail += (
            " If the concept exists under another name or elsewhere, add a pointer in "
            "AGENTS.md (or a comment/alias where agents look). If it does not exist, say so."
        )
        self.add(
            "add-a-pointer",
            "Point agents to what they are searching for",
            detail,
            [signals.SEARCH_MISS],
        )

    # ---- file rules ------------------------------------------------------------------

    def file(self, facts: FileFacts | None) -> None:
        misses = self.get(signals.EDIT_MISS)
        ambiguous = self.get(signals.EDIT_MISS, "ambiguous")
        stale = self.get(signals.STALE_EDIT)
        thrash = self.get(signals.EDIT_THRASH)
        reverts = self.get(signals.EDIT_REVERT)
        rework = self.get(signals.HUMAN_REWORK)
        edit_trouble = [*misses, *stale, *thrash, *reverts]
        generated = facts is not None and facts.generated
        large = facts is not None and facts.lines is not None and facts.lines >= LARGE_FILE_LINES

        if generated and facts is not None and (edit_trouble or rework):
            involved = [*edit_trouble, *rework]
            self.add(
                "edit-the-source-not-the-output",
                "Generated file: point agents at its source",
                f"This file looks generated (judging by {facts.generated_reason}), yet agents "
                f"ran into trouble editing it directly {_in_sessions(involved)}. Say in "
                "AGENTS.md which source to change and which command regenerates it, and "
                "consider denying direct edits to it.",
                [f.signal for f in involved],
            )
        if len(misses) >= MIN_EVENTS and large and facts is not None:
            self.add(
                "split-or-anchor-large-file",
                "Large file: split it or add unique anchors",
                f"{len(misses)} edits failed to locate their target in this {facts.lines}-line "
                f"file ({len(ambiguous)} matched several places, "
                f"{len(misses) - len(ambiguous)} matched nothing) across "
                f"{_sessions(misses)} session(s). Split it into smaller modules, or give "
                "repeated blocks unique nearby text (section comments, distinct names) so "
                "an edit can be targeted.",
                [signals.EDIT_MISS],
            )
        elif len(misses) >= MIN_EVENTS and not generated:
            if len(ambiguous) * 2 >= len(misses):
                detail = (
                    f"{len(ambiguous)} of {len(misses)} failed edits matched several places: "
                    "the file contains repeated blocks. Give them distinguishing text or "
                    "factor the repetition out."
                )
                title = "Repeated blocks: make edit targets unique"
            else:
                detail = (
                    f"{len(misses)} edits in {_sessions(misses)} session(s) did not find the "
                    "text the agent expected. Usual causes: a formatter or hook rewrites the "
                    "file after edits, unusual whitespace (tabs, CRLF), or the file changes "
                    "under the agent. Document the formatting step, or run it in a hook so "
                    "the agent sees the result."
                )
                title = "Agents misremember this file: check what rewrites it"
            self.add("make-edits-land", title, detail, [signals.EDIT_MISS])

        modified = self.get(signals.STALE_EDIT, "modified")
        if len(modified) >= MIN_EVENTS and not generated:
            self.add(
                "document-what-rewrites-this-file",
                "Something rewrites this file between read and write",
                f"Writes were refused {_in_sessions(modified)} because the file changed on "
                "disk after the agent read it. Find the writer (formatter on save, watcher, "
                "code generator, a parallel agent) and document it, or make it run "
                "deterministically at a known point.",
                [signals.STALE_EDIT],
            )

        path_misses = self.get(signals.PATH_MISS)
        if len(path_misses) >= MIN_EVENTS:
            self.add(
                "path-agents-expect",
                "Agents expect this path to exist",
                f"Agents tried to open this non-existent path {_in_sessions(path_misses)}. "
                "Add a line to AGENTS.md saying where this actually lives, or create the "
                "file/alias if the guess is the more natural layout.",
                [signals.PATH_MISS],
            )

        self.corrections()
        self.rejections()
        self.interrupts()

        if len(thrash) + len(reverts) >= MIN_EVENTS:
            self.add(
                "add-a-fast-check",
                "Give agents a fast way to check changes to this file",
                f"Edits here did not converge: {len(thrash)} thrash episode(s) and "
                f"{len(reverts)} reverted edit(s) in {_sessions([*thrash, *reverts])} "
                "session(s). Document the quickest command that validates this file (a "
                "single test, a type check) so agents can verify instead of iterating blind.",
                [f.signal for f in (*thrash, *reverts)],
            )

        if len(rework) >= MIN_EVENTS:
            detail = (
                f"Humans changed this file again shortly after {len(rework)} agent commits "
                f"touched it ({_sessions(rework)} distinct agent commits)."
            )
            shas = sorted({f.detail.get("human_commit", "") for f in rework} - {""})
            detail += f" Follow-up commits: {', '.join(shas[:MAX_QUOTES])}."
            detail += (
                " Read those follow-ups: whatever they fix repeatedly is a convention to "
                "document or a test to add."
            )
            self.add(
                "learn-from-rework",
                "Learn from the human follow-ups",
                detail,
                [signals.HUMAN_REWORK],
            )

        failures = self.get(signals.COMMAND_FAILURE)
        if len(failures) >= MIN_EVENTS:
            detail = f"Commands naming this file failed {_in_sessions(failures)}"
            commands = _top([_command_key(f) for f in failures])
            if commands:
                detail += ": " + ", ".join(
                    f"`{cmd}`" + (f" ({n}x)" if n > 1 else "") for cmd, n in commands
                )
            detail += (
                ". Document how to run or test this file (see the matching entry under commands)."
            )
            self.add(
                "document-how-to-run",
                "Document how to run or test this file",
                detail,
                [signals.COMMAND_FAILURE],
            )

        self.search_misses("this file")

        loops = self.get(signals.READ_LOOP)
        if len(loops) >= MIN_EVENTS:
            size = f" ({facts.lines} lines)" if facts is not None and facts.lines else ""
            self.add(
                "summarize-this-file",
                "Agents keep re-reading this file",
                f"The same part of this file{size} was re-read without progress "
                f"{_in_sessions(loops)}. A short header comment or AGENTS.md note on what "
                "it contains and where the important parts are would save the round trips.",
                [signals.READ_LOOP],
            )

    # ---- command rules ---------------------------------------------------------------

    def command(self, key: str) -> None:
        failures = self.get(signals.COMMAND_FAILURE)
        invocation = self.get(signals.COMMAND_FAILURE, "invocation")
        retries = self.get(signals.RETRY_LOOP)
        fixes = _top([f.detail.get("recovered_by", "") for f in failures], 1)
        if fixes and fixes[0][1] >= MIN_EVENTS:
            fix, count = fixes[0]
            self.add(
                "use-the-working-command",
                f"Tell agents to use `{fix}`",
                f"`{key}` failed {_in_sessions(failures)}; {_times(count)} the next "
                f"successful command was `{fix}`. Add a line to AGENTS.md such as: "
                f'"use `{fix}`, not `{key}`".',
                [signals.COMMAND_FAILURE],
            )
        elif len(invocation) >= MIN_EVENTS:
            detail = f"`{key}` failed {_in_sessions(invocation)} with setup or invocation errors."
            if self.quote is not None:
                lines = _top([_error_line(f) for f in invocation], 2)
                if lines:
                    detail += " Typical output: " + " / ".join(
                        f'"{self.quote(line, QUOTE_CHARS)}"' for line, _ in lines
                    )
                    detail += "."
            detail += (
                " Document the working invocation (directory, environment, arguments) in "
                "AGENTS.md, or wrap it in a script or make target that sets things up."
            )
            self.add(
                "document-the-command",
                f"Document how to run `{key}`",
                detail,
                [signals.COMMAND_FAILURE],
            )
        if retries:
            longest = max(int(f.detail.get("count", "0")) for f in retries)
            self.add(
                "make-the-failure-actionable",
                "Make this failure explain itself",
                f"Agents re-ran `{key}` up to {longest} times in a row without success "
                f"({len(retries)} retry loop(s) in {_sessions(retries)} session(s)). The "
                "output did not lead them to a fix: note the known cause in AGENTS.md, or "
                "make the command fail fast with a message that says what to do.",
                [signals.RETRY_LOOP],
            )
        self.rejections()
        self.interrupts()


def _command_key(finding: Finding) -> str:
    return next((t.key for t in finding.targets if t.kind == model.COMMAND), "")


_NOISE_LINE_RE = re.compile(r"^(?:\$ |exit code \d+|traceback|\s*file \"|\s*at )", re.I)


def _error_line(finding: Finding) -> str:
    """The most telling line of a failed command's output: the last invocation-error line."""
    lines = [ln.strip() for ln in finding.excerpt.splitlines() if ln.strip()]
    for line in reversed(lines):
        if signals.INVOCATION_ERROR_RE.search(line) and not line.startswith("$ "):
            return line
    for line in reversed(lines):
        if not _NOISE_LINE_RE.match(line):
            return line
    return ""


def recommend(
    kind: str,
    key: str,
    findings: Sequence[Finding],
    facts: FileFacts | None = None,
    quote: Quoter | None = None,
    shares: Mapping[int, float] | None = None,
) -> list[dict[str, object]]:
    """Recommendations for one hotspot.

    ``quote`` redacts and truncates verbatim transcript text; pass ``None`` to
    keep all verbatim text out of the recommendations. ``shares`` maps a
    finding's ``fid`` to the fraction of it attributed to this hotspot
    (default 1).
    """
    rules = _Rules(findings, quote, shares or {})
    if kind == model.FILE:
        rules.file(facts)
    elif kind == model.COMMAND:
        rules.command(key)
    else:
        rules.search_misses(f"under {key}/" if key != "." else "the whole repo")
        rules.corrections()
    return rules.out
