def test_a_rule_that_refuses_nothing_says_so(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    (repo / "src").mkdir(parents=True)
    (repo / "src" / "gen.py").write_text(
        "# Code generated by gen.py. DO NOT EDIT.\n# Run `make gen` to regenerate.\nx = 1\n"
    )
    gen = str(repo / "src" / "gen.py")
    for name in ("s1", "s2", "s3"):
        session = Session(name, cwd=str(repo)).user("bump x")
        session.read(gen).edit(gen, "x = 1", "x = 2", error=EDIT_NOT_FOUND)
        session.edit(gen, "x = 1", "x = 3", error=EDIT_NOT_FOUND)
        session.save(tmp_path / "t")
    result = analyze(AnalyzeOptions(repo=repo, transcripts=[tmp_path / "t"], include_git=False))
    (deny,) = result["paste"]["deny"]
    assert deny["rule"] == "Edit(/src/gen.py)"
    assert (deny["would_refuse"], deny["sessions"], deny["other_agent_sessions"]) == (6, 3, 0)
    result["paste"]["deny"][0].update(would_refuse=0, refused_targets=[], sessions=0)
    assert paste_deny(result) == [("Edit(/src/gen.py)", "refuses no call these sessions made")]
